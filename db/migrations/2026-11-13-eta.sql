/* P9 — ETA (Egyptian Tax Authority) e-invoicing.
   Creates the seller configuration and the ETA invoice documents. */

CREATE TABLE IF NOT EXISTS eta_config (
    config_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_name varchar(200),
    seller_vat_number varchar(60),
    seller_address text,
    seller_email varchar(200),
    seller_phone varchar(60),
    seller_registration_id varchar(60),
    seller_logo text,
    egs_uuid varchar(60),
    environment varchar(30) NOT NULL DEFAULT 'sandbox',
    api_base_url varchar(300),
    token_url varchar(300),
    client_id varchar(200),
    client_secret varchar(200),
    private_key text,
    certificate text,
    is_active boolean NOT NULL DEFAULT false,
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS eta_invoices (
    eta_invoice_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id bigint NOT NULL REFERENCES invoices(invoice_id) ON DELETE CASCADE,
    invoice_uuid varchar(60) NOT NULL UNIQUE,
    invoice_type smallint NOT NULL DEFAULT 2,
    xml text,
    qr_data text,
    qr_png_base64 text,
    invoice_hash varchar(200),
    signature text,
    egs_uuid varchar(60),
    public_id varchar(60),
    status smallint NOT NULL DEFAULT 1,
    eta_response jsonb,
    submitted_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_eta_invoices_invoice ON eta_invoices(invoice_id);
ALTER TABLE eta_invoices ADD COLUMN IF NOT EXISTS egs_uuid varchar(60);
