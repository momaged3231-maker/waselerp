CREATE TABLE IF NOT EXISTS reminders (
    reminder_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer NOT NULL REFERENCES branches(branch_id),
    title varchar(300) NOT NULL,
    description text,
    remind_at timestamptz NOT NULL,
    is_done boolean NOT NULL DEFAULT false,
    done_at timestamptz,
    created_by integer REFERENCES users(user_id),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_reminders_branch_date ON reminders(branch_id, remind_at);
CREATE INDEX IF NOT EXISTS ix_reminders_done ON reminders(is_done, remind_at);

ALTER TABLE parties ADD COLUMN IF NOT EXISTS reminder_note text;
