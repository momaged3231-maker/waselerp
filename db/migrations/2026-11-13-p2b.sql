/* P2 (part 2) — coupons, gift offers, payment allocation, shipments,
   invoice editing and multi-method payments. */

CREATE TABLE IF NOT EXISTS invoice_payments (
    invoice_payment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id bigint NOT NULL REFERENCES invoices(invoice_id) ON DELETE CASCADE,
    payment_method smallint NOT NULL DEFAULT 1,
    amount numeric(18,2) NOT NULL CHECK (amount > 0),
    cash_account_id integer REFERENCES cash_accounts(cash_account_id),
    reference_no varchar(60),
    notes text,
    created_by integer REFERENCES users(user_id),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_invoice_payments_invoice ON invoice_payments(invoice_id);

ALTER TABLE invoices ADD COLUMN IF NOT EXISTS coupon_code varchar(40);

CREATE TABLE IF NOT EXISTS coupons (
    coupon_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(40) NOT NULL UNIQUE,
    name varchar(200),
    discount_type smallint NOT NULL DEFAULT 1,
    discount_value numeric(18,4) NOT NULL DEFAULT 0,
    min_invoice_amount numeric(18,2) NOT NULL DEFAULT 0,
    max_discount numeric(18,2),
    branch_id integer REFERENCES branches(branch_id),
    start_date date,
    end_date date,
    usage_limit integer,
    used_count integer NOT NULL DEFAULT 0,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_coupons_active ON coupons(is_active);

CREATE TABLE IF NOT EXISTS gift_offers (
    gift_offer_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL,
    source_item_id integer NOT NULL REFERENCES items(item_id),
    source_quantity numeric(18,6) NOT NULL DEFAULT 1,
    gift_item_id integer NOT NULL REFERENCES items(item_id),
    gift_quantity numeric(18,6) NOT NULL DEFAULT 1,
    gift_unit_id integer REFERENCES units(unit_id),
    bundle_price numeric(18,4),
    start_date date,
    end_date date,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS invoice_allocations (
    allocation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_id bigint REFERENCES vouchers(voucher_id) ON DELETE CASCADE,
    invoice_id bigint NOT NULL REFERENCES invoices(invoice_id) ON DELETE CASCADE,
    amount numeric(18,2) NOT NULL CHECK (amount > 0),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_invoice_allocations_invoice ON invoice_allocations(invoice_id);
CREATE INDEX IF NOT EXISTS ix_invoice_allocations_voucher ON invoice_allocations(voucher_id);

CREATE TABLE IF NOT EXISTS shipments (
    shipment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_no varchar(60) NOT NULL,
    invoice_id bigint REFERENCES invoices(invoice_id),
    order_id bigint REFERENCES orders(order_id),
    branch_id integer NOT NULL REFERENCES branches(branch_id),
    status smallint NOT NULL DEFAULT 1,
    delivery_method smallint NOT NULL DEFAULT 1,
    carrier_name varchar(200),
    tracking_no varchar(80),
    ship_date date,
    delivered_at timestamptz,
    recipient_name varchar(200),
    recipient_phone varchar(60),
    delivery_address text,
    delivery_fee numeric(18,2) NOT NULL DEFAULT 0,
    notes text,
    created_by integer REFERENCES users(user_id),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (branch_id, shipment_no)
);
CREATE INDEX IF NOT EXISTS ix_shipments_invoice ON shipments(invoice_id);
CREATE INDEX IF NOT EXISTS ix_shipments_status ON shipments(status);
