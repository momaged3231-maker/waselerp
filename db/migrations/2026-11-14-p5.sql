CREATE TABLE IF NOT EXISTS customer_groups (
    customer_group_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL,
    name_en varchar(200),
    notes text,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (name)
);
CREATE INDEX IF NOT EXISTS ix_customer_groups_active ON customer_groups(is_active);

CREATE TABLE IF NOT EXISTS customer_classifications (
    classification_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL,
    name_en varchar(200),
    discount_pct numeric(9,4) NOT NULL DEFAULT 0,
    credit_limit numeric(18,2) NOT NULL DEFAULT 0,
    grace_days integer NOT NULL DEFAULT 0,
    notes text,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (name)
);
CREATE INDEX IF NOT EXISTS ix_customer_classifications_active ON customer_classifications(is_active);

ALTER TABLE parties ADD COLUMN IF NOT EXISTS customer_group_id bigint REFERENCES customer_groups(customer_group_id);
ALTER TABLE parties ADD COLUMN IF NOT EXISTS classification_id bigint REFERENCES customer_classifications(classification_id);
