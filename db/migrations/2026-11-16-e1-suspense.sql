-- E1-B — suspense account plumbing for unclassified bank movements.
-- The BANK_SUSPENSE GL account itself (2106, «حركات بنكية غير مصنفة») is seeded by
-- src/cli/seed.ts (CHART entry with mapping BANK_SUSPENSE) — run the seed after migrating.
-- This migration adds the per-movement tracking table only.

CREATE TABLE IF NOT EXISTS bank_suspense_entries (
    suspense_entry_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    adjustment_journal_id bigint NOT NULL REFERENCES gl_journals(journal_id),
    suspense_gl_entry_id  bigint NOT NULL REFERENCES gl_entries(entry_id),
    bank_statement_line_id bigint NOT NULL REFERENCES bank_statement_lines(line_id),
    -- 1 = deposit side (suspense carries a CREDIT until classified)
    -- 2 = withdrawal side (suspense carries a DEBIT until classified)
    direction             smallint NOT NULL,
    amount                numeric(18,2) NOT NULL,
    -- 1 open · 2 classified · 3 reversed by run reversal
    status                smallint NOT NULL DEFAULT 1,
    classification_journal_id bigint REFERENCES gl_journals(journal_id),
    classified_account_id integer REFERENCES gl_accounts(account_id),
    classified_by         integer REFERENCES users(user_id),
    classified_at         timestamptz,
    notes                 text,
    created_at            timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_bank_suspense_status ON bank_suspense_entries(status);
CREATE INDEX IF NOT EXISTS ix_bank_suspense_line ON bank_suspense_entries(bank_statement_line_id);
CREATE INDEX IF NOT EXISTS ix_bank_suspense_journal ON bank_suspense_entries(adjustment_journal_id);
