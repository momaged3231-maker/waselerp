-- ------------------------------------------------------------------
--  2.  Purchase orders — per-PO delivery terms only
-- ------------------------------------------------------------------
-- C-4: goods_received_by / goods_received_at MOVED to purchase_receipts
-- (received_by / inspected_by below). Do NOT add them to orders.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS delivery_terms varchar(40);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS delivery_terms_note text;

-- ------------------------------------------------------------------
--  3.  Goods receipt header  (GRN / محضر استلام البضاعة)
-- ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS purchase_receipts (
    receipt_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_no      varchar(60)  NOT NULL,
    branch_id       integer      NOT NULL REFERENCES branches(branch_id),   -- receiving branch (GRNI dimension)
    warehouse_id    integer      NOT NULL REFERENCES warehouses(warehouse_id),
    order_id        bigint       NULL REFERENCES orders(order_id),
    party_id        integer      NULL REFERENCES parties(party_id),          -- supplier (GRNI dimension)
    receipt_date    date         NOT NULL DEFAULT CURRENT_DATE,
    invoice_id      bigint       NULL REFERENCES invoices(invoice_id),
    -- 1 inspected + accepted (مخزن), 2 under inspection, 3 partially rejected,
    -- 4 fully rejected / returned to supplier, 5 cancelled draft
    status         smallint     NOT NULL DEFAULT 1,
    received_by    integer      NOT NULL REFERENCES users(user_id),          -- C-4: receiver identity
    inspected_by   integer      NULL REFERENCES users(user_id),
    external_inspector_name text NULL,   -- OI-13: external inspector (government inspector, etc.) — used only when inspected_by points to system user and external party is documented
    inspected_at   timestamptz  NULL,
    notes          text         NULL,
    created_by     integer      NOT NULL REFERENCES users(user_id),
    created_at     timestamptz  NOT NULL DEFAULT now(),
    updated_at     timestamptz  NOT NULL DEFAULT now(),
    -- GL linkage (populated by the engine, never by UI)
    gl_journal_id  bigint       NULL REFERENCES gl_journals(journal_id),
    posting_status smallint     NULL,   -- 1 pending, 2 posted, 3 reversed (D-13: renamed from gl_kind)
    UNIQUE (branch_id, receipt_no)
);
CREATE INDEX IF NOT EXISTS ix_purchase_receipts_order  ON purchase_receipts(order_id);
CREATE INDEX IF NOT EXISTS ix_purchase_receipts_branch ON purchase_receipts(branch_id);
CREATE INDEX IF NOT EXISTS ix_purchase_receipts_party  ON purchase_receipts(party_id);

-- ------------------------------------------------------------------
--  4.  Goods receipt lines
-- ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS purchase_receipt_lines (
    line_id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id          bigint NOT NULL REFERENCES purchase_receipts(receipt_id) ON DELETE CASCADE,
    line_no             smallint NOT NULL,
    order_line_id       bigint NULL REFERENCES order_lines(order_line_id),
    item_id             integer NOT NULL REFERENCES items(item_id),
    unit_id             integer NOT NULL REFERENCES units(unit_id),
    ordered_qty         numeric(18,6) NULL,
    received_qty        numeric(18,6) NOT NULL,
    accepted_qty        numeric(18,6) NOT NULL DEFAULT 0,
    rejected_qty        numeric(18,6) NOT NULL DEFAULT 0,   -- memo only (R-4 option a)
    missing_qty         numeric(18,6) NOT NULL DEFAULT 0,   -- memo only
    damaged_qty         numeric(18,6) NOT NULL DEFAULT 0,   -- memo only
    unit_cost           numeric(18,4) NOT NULL,
    -- stored because the line may span two invoices or be sent to quarantine
    cost_value          numeric(18,2) GENERATED ALWAYS AS (accepted_qty * unit_cost) STORED,
    reason              text,
    inspected_by        integer NULL REFERENCES users(user_id),
    inspected_at        timestamptz NULL,
    created_at          timestamptz NOT NULL DEFAULT now(),
    UNIQUE (receipt_id, line_no)
);
CREATE INDEX IF NOT EXISTS ix_purchase_receipt_lines_receipt ON purchase_receipt_lines(receipt_id);
CREATE INDEX IF NOT EXISTS ix_purchase_receipt_lines_item    ON purchase_receipt_lines(item_id);

-- ------------------------------------------------------------------
--  5.  Rejection log per line (audit trail) — memo only, no valuation
-- ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS purchase_rejections (
    rejection_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    line_id         bigint NOT NULL REFERENCES purchase_receipt_lines(line_id) ON DELETE CASCADE,
    rejected_qty    numeric(18,6) NOT NULL,
    reason          text NOT NULL,
    decision        smallint NOT NULL DEFAULT 6,
    -- 1 replace, 2 accept-with-discount (authorized), 3 return+claim,
    -- 4 scrap, 5 pending, 6 pending decision (default)
    decided_by      integer NULL REFERENCES users(user_id),
    decided_at      timestamptz NULL,
    notes           text,
    created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_purchase_rejections_line ON purchase_rejections(line_id);

-- ------------------------------------------------------------------
--  6.  Supplier claims / debit notes / credits
-- ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS supplier_claims (
    claim_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id        integer NOT NULL REFERENCES parties(party_id),
    receipt_id      bigint NULL REFERENCES purchase_receipts(receipt_id),
    invoice_id      bigint NULL REFERENCES invoices(invoice_id),
    branch_id       integer NOT NULL REFERENCES branches(branch_id),
    claim_no        varchar(40) NOT NULL,
    -- 1 shortage, 2 damaged, 3 wrong item, 4 price variance, 5 over-shipment, 6 other
    claim_type      smallint NOT NULL DEFAULT 1,
    claimed_qty     numeric(18,6) NULL,
    claim_amount    numeric(18,2) NOT NULL,
    status          smallint NOT NULL DEFAULT 1,
    -- 1 open, 2 debit note issued, 3 credit received, 4 replacement, 5 written off, 6 closed
    settlement      smallint NULL,
    notes           text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (branch_id, claim_no)
);
CREATE INDEX IF NOT EXISTS ix_supplier_claims_party ON supplier_claims(party_id);

-- ------------------------------------------------------------------
--  7.  Supplier advances (مقدمات الموردين) — asset, party dimension only
-- ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS supplier_advances (
    advance_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id            integer NOT NULL REFERENCES parties(party_id),
    branch_id           integer      NOT NULL REFERENCES branches(branch_id),   -- operational (not accounting dimension)
    order_id            bigint NULL REFERENCES orders(order_id),
    advance_no          varchar(60) NOT NULL,
    amount              numeric(18,2) NOT NULL,
    paid_amount         numeric(18,2) NOT NULL DEFAULT 0,
    still_open          numeric(18,2) NOT NULL DEFAULT 0,
    -- JSON of applied allocations: [{invoice_id, amount, applied_at}]
    allocations         jsonb NOT NULL DEFAULT '[]'::jsonb,
    status              smallint NOT NULL DEFAULT 1,
    -- 1 open/unallocated, 2 partial, 3 fully applied, 4 cancelled/refunded
    notes               text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    settled_at          timestamptz NULL,
    UNIQUE (branch_id, advance_no)
);
CREATE INDEX IF NOT EXISTS ix_supplier_advances_party ON supplier_advances(party_id);

-- ------------------------------------------------------------------
--  8.  Supplier payment allocations (ربط سند صرف بفواتير مفردة)
-- ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS supplier_payment_allocations (
    allocation_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_id      bigint NOT NULL REFERENCES vouchers(voucher_id) ON DELETE RESTRICT,
    invoice_id      bigint NOT NULL REFERENCES invoices(invoice_id),
    amount          numeric(18,2) NOT NULL CHECK (amount > 0),
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (voucher_id, invoice_id)
);
-- NOTE: voucher_type = 2 (صرف) enforced in API, not in schema.
CREATE INDEX IF NOT EXISTS ix_supplier_payment_allocations_inv ON supplier_payment_allocations(invoice_id);

-- ------------------------------------------------------------------
--  9.  Partial invoice ↔ receipt mapping (three-way match support)
-- ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS purchase_invoice_links (
    link_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id      bigint NOT NULL REFERENCES invoices(invoice_id),
    receipt_id      bigint NOT NULL REFERENCES purchase_receipts(receipt_id),
    receipt_line_id bigint NULL REFERENCES purchase_receipt_lines(line_id),
    item_id         integer NOT NULL REFERENCES items(item_id),
    invoiced_qty    numeric(18,6) NOT NULL CHECK (invoiced_qty > 0),
    voided_at       timestamptz NULL,   -- DEC-PURCH-047: set on invoice void; excluded from v_open_purchase_lines
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (invoice_id, receipt_id, receipt_line_id, item_id)
);
CREATE INDEX IF NOT EXISTS ix_purchase_invoice_links_inv     ON purchase_invoice_links(invoice_id);
CREATE INDEX IF NOT EXISTS ix_purchase_invoice_links_receipt ON purchase_invoice_links(receipt_id);

-- ------------------------------------------------------------------
--  10. Three-way match overrides — conscious exceptions (R-5)
-- ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS purchase_match_overrides (
    override_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id      bigint NOT NULL REFERENCES invoices(invoice_id),
    order_id        bigint NULL REFERENCES orders(order_id),
    receipt_id      bigint NULL REFERENCES purchase_receipts(receipt_id),
    overridden_by   integer NOT NULL REFERENCES users(user_id),
    reason          text NOT NULL,
    overridden_at   timestamptz NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------------
--  11.  View: open (uninvoiced) purchase lines — single source of truth
-- ------------------------------------------------------------------
--  Mirrors v_invoice_overdue pattern on the sales side.
--  Every consumer (GRN slice, settlement slice, reports) reads from this view.
--  open_qty = accepted_qty - SUM(invoiced_qty) from purchase_invoice_links.
CREATE OR REPLACE VIEW v_open_purchase_lines AS
SELECT
    prl.line_id            AS receipt_line_id,
    prl.receipt_id,
    prl.item_id,
    prl.unit_id,
    prl.accepted_qty,
    COALESCE(SUM(pil.invoiced_qty), 0) AS invoiced_qty,
    prl.accepted_qty - COALESCE(SUM(pil.invoiced_qty), 0) AS open_qty,
    prl.unit_cost,
    (prl.accepted_qty - COALESCE(SUM(pil.invoiced_qty), 0)) * prl.unit_cost AS open_value,
    pr.branch_id            AS branch_id,
    pr.party_id             AS party_id,
    pr.receipt_date
FROM purchase_receipt_lines prl
JOIN purchase_receipts pr ON pr.receipt_id = prl.receipt_id
LEFT JOIN purchase_invoice_links pil ON pil.receipt_line_id = prl.line_id AND pil.voided_at IS NULL
WHERE prl.accepted_qty > 0
GROUP BY prl.line_id, prl.receipt_id, prl.item_id, prl.unit_id,
         prl.accepted_qty, prl.unit_cost, pr.branch_id, pr.party_id, pr.receipt_date
HAVING prl.accepted_qty - COALESCE(SUM(pil.invoiced_qty), 0) > 0;

