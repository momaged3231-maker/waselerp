CREATE TABLE IF NOT EXISTS held_invoices (
    held_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    held_no varchar(60) NOT NULL,
    branch_id integer NOT NULL REFERENCES branches(branch_id),
    party_id integer REFERENCES parties(party_id),
    customer_name varchar(200),
    warehouse_id integer REFERENCES warehouses(warehouse_id),
    payload jsonb NOT NULL,
    total_amount numeric(18,2) NOT NULL DEFAULT 0,
    notes text,
    created_by integer REFERENCES users(user_id),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_held_invoices_branch ON held_invoices(branch_id);

CREATE TABLE IF NOT EXISTS restaurant_tables (
    table_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer NOT NULL REFERENCES branches(branch_id),
    name varchar(100) NOT NULL,
    table_type smallint NOT NULL DEFAULT 1,
    capacity integer NOT NULL DEFAULT 4,
    is_active boolean NOT NULL DEFAULT true,
    notes text,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (branch_id, name)
);

CREATE TABLE IF NOT EXISTS item_modifiers (
    modifier_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id integer NOT NULL REFERENCES items(item_id) ON DELETE CASCADE,
    name varchar(200) NOT NULL,
    price numeric(18,4) NOT NULL DEFAULT 0,
    is_active boolean NOT NULL DEFAULT true
);
CREATE INDEX IF NOT EXISTS ix_item_modifiers_item ON item_modifiers(item_id);

CREATE TABLE IF NOT EXISTS table_orders (
    table_order_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no varchar(60) NOT NULL,
    branch_id integer NOT NULL REFERENCES branches(branch_id),
    table_id integer REFERENCES restaurant_tables(table_id),
    party_id integer REFERENCES parties(party_id),
    guest_count integer NOT NULL DEFAULT 1,
    status smallint NOT NULL DEFAULT 1,
    subtotal numeric(18,2) NOT NULL DEFAULT 0,
    tax_amount numeric(18,2) NOT NULL DEFAULT 0,
    total_amount numeric(18,2) NOT NULL DEFAULT 0,
    notes text,
    invoice_id bigint REFERENCES invoices(invoice_id),
    created_by integer REFERENCES users(user_id),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (branch_id, order_no)
);
CREATE INDEX IF NOT EXISTS ix_table_orders_status ON table_orders(status);

CREATE TABLE IF NOT EXISTS table_order_lines (
    table_order_line_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_order_id bigint NOT NULL REFERENCES table_orders(table_order_id) ON DELETE CASCADE,
    line_number integer NOT NULL,
    item_id integer NOT NULL REFERENCES items(item_id),
    unit_id integer NOT NULL REFERENCES units(unit_id),
    quantity numeric(18,6) NOT NULL DEFAULT 1,
    unit_price numeric(18,4) NOT NULL DEFAULT 0,
    discount_pct numeric(9,4) NOT NULL DEFAULT 0,
    tax_pct numeric(9,4) NOT NULL DEFAULT 0,
    line_total numeric(18,2) NOT NULL DEFAULT 0,
    notes text,
    kitchen_status smallint NOT NULL DEFAULT 1
);

