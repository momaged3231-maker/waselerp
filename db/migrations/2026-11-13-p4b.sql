/* P4.2 — stock vouchers (أذون المخازن): incoming / outgoing / damage / opening.
   Draft → approve → apply movements + post journal. Depends on gl_journals. */

CREATE TABLE IF NOT EXISTS stock_vouchers (
    stock_voucher_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_no varchar(60) NOT NULL,
    voucher_date date NOT NULL DEFAULT CURRENT_DATE,
    branch_id integer NOT NULL REFERENCES branches(branch_id),
    warehouse_id integer NOT NULL REFERENCES warehouses(warehouse_id),
    voucher_type smallint NOT NULL,
    status smallint NOT NULL DEFAULT 1,
    notes text,
    gl_journal_id bigint REFERENCES gl_journals(journal_id),
    created_by integer NOT NULL REFERENCES users(user_id),
    approved_by integer REFERENCES users(user_id),
    approved_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (branch_id, voucher_no)
);
CREATE INDEX IF NOT EXISTS ix_stock_vouchers_warehouse ON stock_vouchers(warehouse_id, status);

CREATE TABLE IF NOT EXISTS stock_voucher_lines (
    stock_voucher_line_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_voucher_id bigint NOT NULL REFERENCES stock_vouchers(stock_voucher_id) ON DELETE CASCADE,
    line_number integer NOT NULL,
    item_id integer NOT NULL REFERENCES items(item_id),
    unit_id integer NOT NULL REFERENCES units(unit_id),
    quantity numeric(18,6) NOT NULL DEFAULT 0,
    unit_cost numeric(18,4) NOT NULL DEFAULT 0,
    serial_no varchar(100),
    expiry_date date,
    notes text
);
CREATE INDEX IF NOT EXISTS ix_stock_voucher_lines_voucher ON stock_voucher_lines(stock_voucher_id);

