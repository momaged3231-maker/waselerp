-- E6 sign-off — separating manual administrative lock from accounting close,
-- plus an immutable audit trail for E3/E5 pre-close overrides.
-- Idempotent: safe to re-apply (IF NOT EXISTS everywhere).

ALTER TABLE periods
    ADD COLUMN IF NOT EXISTS manual_lock        boolean NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS manual_lock_at     timestamptz,
    ADD COLUMN IF NOT EXISTS manual_lock_by     integer REFERENCES users(user_id),
    ADD COLUMN IF NOT EXISTS manual_lock_reason text;

-- One manual-lock marker per period is enforced by the single set of columns;
-- the current lock always lives on the periods row. No history row table to
-- keep referential integrity with branches/users trivial.
CREATE INDEX IF NOT EXISTS ix_periods_manual_lock ON periods(manual_lock) WHERE manual_lock;

-- Immutable override register for the two due-checks. Rows are written inside
-- the closing transaction; there are deliberately NO endpoints to update or
-- delete them, and the UNIQUE constraint prevents double-counting the same
-- override for a period+check+due.
CREATE TABLE IF NOT EXISTS period_close_overrides (
    override_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_id      integer NOT NULL REFERENCES periods(period_id) ON DELETE CASCADE,
    branch_id      integer NOT NULL REFERENCES branches(branch_id),
    check_code     varchar(60) NOT NULL,          -- e3_bank_expense_due | e5_depreciation_due
    due_key        varchar(160) NOT NULL,         -- 'rule:<id>:<YYYY-MM-DD>' | 'asset:<id>:<YYYY-MM>'
    due_label      text NOT NULL,                 -- Arabic human label of the due item
    due_amount     numeric(18,2),                 -- the overridden amount (fee / depreciation)
    reason         text NOT NULL,
    created_by     integer NOT NULL REFERENCES users(user_id),
    created_at     timestamptz NOT NULL DEFAULT now(),
    UNIQUE (period_id, check_code, due_key)
);
CREATE INDEX IF NOT EXISTS ix_period_close_overrides_period ON period_close_overrides(period_id, check_code);
