/* P2 — price lists, quotations and orders.
   Run after db/schema.postgres.sql, then `npm run db:seed` to create the
   default price lists (نقدي / جملة). */

ALTER TABLE price_lists ADD COLUMN IF NOT EXISTS code varchar(50);
ALTER TABLE price_lists ADD COLUMN IF NOT EXISTS list_type smallint NOT NULL DEFAULT 1;
ALTER TABLE price_lists ADD COLUMN IF NOT EXISTS branch_id integer REFERENCES branches(branch_id);
ALTER TABLE price_lists ADD COLUMN IF NOT EXISTS priority integer NOT NULL DEFAULT 0;
ALTER TABLE price_lists ADD COLUMN IF NOT EXISTS discount_pct numeric(9,4) NOT NULL DEFAULT 0;
ALTER TABLE price_lists ADD COLUMN IF NOT EXISTS start_date date;
ALTER TABLE price_lists ADD COLUMN IF NOT EXISTS end_date date;
ALTER TABLE price_list_lines ADD COLUMN IF NOT EXISTS min_price numeric(18,4) NOT NULL DEFAULT 0;
ALTER TABLE price_list_lines ADD COLUMN IF NOT EXISTS start_date date;
ALTER TABLE price_list_lines ADD COLUMN IF NOT EXISTS end_date date;
ALTER TABLE parties ADD COLUMN IF NOT EXISTS price_list_id integer REFERENCES price_lists(price_list_id);
CREATE INDEX IF NOT EXISTS ix_price_lists_branch ON price_lists(branch_id);
CREATE UNIQUE INDEX IF NOT EXISTS ux_price_lists_code ON price_lists(code);
CREATE INDEX IF NOT EXISTS ix_price_list_lines_key ON price_list_lines(price_list_id, item_id);

CREATE TABLE IF NOT EXISTS invoice_payments (
    invoice_payment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id bigint NOT NULL REFERENCES invoices(invoice_id) ON DELETE CASCADE,
    -- 1 cash, 2 card, 3 bank transfer, 4 wallet, 5 cheque
    payment_method smallint NOT NULL DEFAULT 1,
    amount numeric(18,2) NOT NULL CHECK (amount > 0),
    cash_account_id integer REFERENCES cash_accounts(cash_account_id),
    reference_no varchar(60),
    notes text,
    created_by integer REFERENCES users(user_id),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_invoice_payments_invoice ON invoice_payments(invoice_id);

CREATE TABLE IF NOT EXISTS quotations (
    quotation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_no varchar(60) NOT NULL,
    quotation_date date NOT NULL DEFAULT CURRENT_DATE,
    valid_until date,
    branch_id integer NOT NULL REFERENCES branches(branch_id),
    party_id integer REFERENCES parties(party_id),
    price_list_id integer REFERENCES price_lists(price_list_id),
    warehouse_id integer REFERENCES warehouses(warehouse_id),
    status smallint NOT NULL DEFAULT 1,
    subtotal numeric(18,2) NOT NULL DEFAULT 0,
    discount_amount numeric(18,2) NOT NULL DEFAULT 0,
    tax_amount numeric(18,2) NOT NULL DEFAULT 0,
    total_amount numeric(18,2) NOT NULL DEFAULT 0,
    notes text,
    converted_invoice_id bigint REFERENCES invoices(invoice_id),
    created_by integer NOT NULL REFERENCES users(user_id),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (branch_id, quotation_no)
);
CREATE INDEX IF NOT EXISTS ix_quotations_party ON quotations(party_id);
CREATE INDEX IF NOT EXISTS ix_quotations_status ON quotations(status);

CREATE TABLE IF NOT EXISTS quotation_lines (
    quotation_line_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_id bigint NOT NULL REFERENCES quotations(quotation_id) ON DELETE CASCADE,
    line_number integer NOT NULL,
    item_id integer NOT NULL REFERENCES items(item_id),
    unit_id integer NOT NULL REFERENCES units(unit_id),
    quantity numeric(18,6) NOT NULL DEFAULT 1,
    unit_price numeric(18,4) NOT NULL DEFAULT 0,
    discount_pct numeric(9,4) NOT NULL DEFAULT 0,
    tax_pct numeric(9,4) NOT NULL DEFAULT 0,
    line_total numeric(18,2) NOT NULL DEFAULT 0,
    notes text
);

CREATE TABLE IF NOT EXISTS orders (
    order_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no varchar(60) NOT NULL,
    order_date date NOT NULL DEFAULT CURRENT_DATE,
    expected_date date,
    branch_id integer NOT NULL REFERENCES branches(branch_id),
    party_id integer REFERENCES parties(party_id),
    warehouse_id integer REFERENCES warehouses(warehouse_id),
    order_type smallint NOT NULL DEFAULT 1,
    status smallint NOT NULL DEFAULT 1,
    subtotal numeric(18,2) NOT NULL DEFAULT 0,
    discount_amount numeric(18,2) NOT NULL DEFAULT 0,
    tax_amount numeric(18,2) NOT NULL DEFAULT 0,
    total_amount numeric(18,2) NOT NULL DEFAULT 0,
    notes text,
    converted_invoice_id bigint REFERENCES invoices(invoice_id),
    created_by integer NOT NULL REFERENCES users(user_id),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (branch_id, order_no)
);
CREATE INDEX IF NOT EXISTS ix_orders_party ON orders(party_id);
CREATE INDEX IF NOT EXISTS ix_orders_status ON orders(status);

CREATE TABLE IF NOT EXISTS order_lines (
    order_line_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    line_number integer NOT NULL,
    item_id integer NOT NULL REFERENCES items(item_id),
    unit_id integer NOT NULL REFERENCES units(unit_id),
    quantity numeric(18,6) NOT NULL DEFAULT 1,
    delivered_qty numeric(18,6) NOT NULL DEFAULT 0,
    unit_price numeric(18,4) NOT NULL DEFAULT 0,
    discount_pct numeric(9,4) NOT NULL DEFAULT 0,
    tax_pct numeric(9,4) NOT NULL DEFAULT 0,
    line_total numeric(18,2) NOT NULL DEFAULT 0,
    notes text
);
