-- TD-53/54 Phase 2 (P2-01) — Supplier credit notes (DEC-PURCH-027 v2.1).
-- Standalone table (not invoice_type=7): CN is a settlement document, not an
-- open invoice; keeps v_invoice_overdue / aging reports clean.
-- No inventory effect; claim_id stays NULL until Phase 4.

CREATE TABLE IF NOT EXISTS supplier_credit_notes (
  credit_note_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch_id           integer NOT NULL REFERENCES branches(branch_id),
  party_id            integer NOT NULL REFERENCES parties(party_id),
  original_invoice_id bigint NOT NULL REFERENCES invoices(invoice_id),
  credit_note_no      varchar(40) NOT NULL,
  cn_date             date NOT NULL,
  subtotal            numeric(18,2) NOT NULL CHECK (subtotal > 0),
  tax_amount          numeric(18,2) NOT NULL DEFAULT 0 CHECK (tax_amount >= 0),
  total_amount        numeric(18,2) GENERATED ALWAYS AS (subtotal + tax_amount) STORED,
  status              smallint NOT NULL DEFAULT 2,  -- 2 posted, 3 cancelled
  gl_journal_id       bigint NULL REFERENCES gl_journals(journal_id),
  reason              text NOT NULL,
  created_by          integer NOT NULL REFERENCES users(user_id),
  posted_at           timestamptz NOT NULL DEFAULT now(),
  cancelled_at        timestamptz NULL,
  cancel_reason       text NULL,
  cancel_journal_id   bigint NULL REFERENCES gl_journals(journal_id),
  client_request_id   varchar(64),
  claim_id            bigint NULL REFERENCES supplier_claims(claim_id),
  created_at          timestamptz NOT NULL DEFAULT now(),
  UNIQUE (branch_id, credit_note_no)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_scn_client_request
  ON supplier_credit_notes(client_request_id)
  WHERE client_request_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_scn_party ON supplier_credit_notes(party_id);
CREATE INDEX IF NOT EXISTS ix_scn_original ON supplier_credit_notes(original_invoice_id);
