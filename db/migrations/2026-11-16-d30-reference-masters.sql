-- Reference masters for definitions: banks, colors, sizes, governorates (D30)

CREATE TABLE IF NOT EXISTS banks (
    bank_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       varchar(30),
    name       varchar(200) NOT NULL,
    name_en    varchar(200),
    is_active  boolean NOT NULL DEFAULT true,
    notes      text,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS colors (
    color_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       varchar(30),
    name       varchar(120) NOT NULL,
    name_en    varchar(120),
    hex_value  varchar(20),
    is_active  boolean NOT NULL DEFAULT true,
    notes      text
);

CREATE TABLE IF NOT EXISTS sizes (
    size_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       varchar(30),
    name       varchar(120) NOT NULL,
    name_en    varchar(120),
    sort_order integer NOT NULL DEFAULT 0,
    is_active  boolean NOT NULL DEFAULT true,
    notes      text
);

CREATE TABLE IF NOT EXISTS governorates (
    governorate_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           varchar(30),
    name           varchar(200) NOT NULL,
    name_en        varchar(200),
    country_id     integer REFERENCES countries(country_id),
    country_code   varchar(10),
    shipping_fees  numeric(18,2) NOT NULL DEFAULT 0,
    is_active      boolean NOT NULL DEFAULT true,
    notes          text
);

-- optional link from cash_accounts to banks master (keeps bank_name for compatibility)
ALTER TABLE cash_accounts ADD COLUMN IF NOT EXISTS bank_id integer REFERENCES banks(bank_id);
CREATE INDEX IF NOT EXISTS ix_cash_accounts_bank ON cash_accounts(bank_id);
CREATE INDEX IF NOT EXISTS ix_governorates_country ON governorates(country_id);
