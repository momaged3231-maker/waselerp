/* P4.3 — stock transfers (تحويل غير مباشر بين مخازن).
   trasfer indirect: خرج من مخزن fonte → استلام في مخزن الوجهة.
   الحالة: draft → outbound (أذن صادر) → received (أذن وارد) → completed.
   Depends on stock_vouchers / gl_journals. */

CREATE TABLE IF NOT EXISTS stock_transfers (
    stock_transfer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_no varchar(60) NOT NULL,
    transfer_date date NOT NULL DEFAULT CURRENT_DATE,
    branch_id integer NOT NULL REFERENCES branches(branch_id),
    from_warehouse_id integer NOT NULL REFERENCES warehouses(warehouse_id),
    to_warehouse_id integer NOT NULL REFERENCES warehouses(warehouse_id),
    status smallint NOT NULL DEFAULT 1,
    outbound_voucher_id bigint REFERENCES stock_vouchers(stock_voucher_id),
    inbound_voucher_id bigint REFERENCES stock_vouchers(stock_voucher_id),
    gl_journal_id bigint REFERENCES gl_journals(journal_id),
    notes text,
    created_by integer NOT NULL REFERENCES users(user_id),
    approved_by integer REFERENCES users(user_id),
    approved_at timestamptz,
    received_at timestamptz,
    completed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (branch_id, transfer_no)
);
CREATE INDEX IF NOT EXISTS ix_stock_transfers_warehouses ON stock_transfers(from_warehouse_id, to_warehouse_id, status);

CREATE TABLE IF NOT EXISTS stock_transfer_lines (
    stock_transfer_line_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_transfer_id bigint NOT NULL REFERENCES stock_transfers(stock_transfer_id) ON DELETE CASCADE,
    line_number integer NOT NULL,
    item_id integer NOT NULL REFERENCES items(item_id),
    unit_id integer NOT NULL REFERENCES units(unit_id),
    quantity numeric(18,6) NOT NULL DEFAULT 0,
    unit_cost numeric(18,4) NOT NULL DEFAULT 0,
    serial_no varchar(100),
    expiry_date date,
    notes text
);
CREATE INDEX IF NOT EXISTS ix_stock_transfer_lines_transfer ON stock_transfer_lines(stock_transfer_id);
