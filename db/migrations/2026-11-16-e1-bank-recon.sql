-- E1 — Bank Reconciliation (المطابقة البنكية)
-- Isolated tables only. No changes to existing accounting tables.
-- All journals still go through common/posting.ts (source_type = 'bank_recon').
-- Lines are never deleted — permanent audit trail.

-- E1.1 — bank statement lines (the paper/imported statement made digital)
CREATE TABLE IF NOT EXISTS bank_statement_lines (
    line_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_account_id    integer NOT NULL REFERENCES cash_accounts(cash_account_id),
    branch_id          integer NOT NULL REFERENCES branches(branch_id),
    statement_date     date NOT NULL,
    value_date         date,
    description        text NOT NULL,
    reference          varchar(80),
    -- 1 deposit · 2 withdrawal · 3 fee · 4 interest · 5 check-deposit ·
    -- 6 check-bounced (customer) · 7 check-bounced (ours) · 8 transfer-in · 9 transfer-out ·
    -- 10 pending-deposit (timing) · 11 outstanding-check (timing)
    movement_type      smallint NOT NULL DEFAULT 1,
    -- signed: + in to the bank, − out of the bank
    amount             numeric(18,2) NOT NULL,
    balance_after      numeric(18,2),
    matched_entry_id   bigint REFERENCES gl_entries(entry_id),
    matched_journal_id bigint REFERENCES gl_journals(journal_id),
    -- 1 unreconciled · 2 auto-matched · 3 manual-matched · 4 timing/pending · 5 disputed · 6 partial-match
    status             smallint NOT NULL DEFAULT 1,
    match_difference   numeric(18,2) NOT NULL DEFAULT 0,
    import_batch_id    uuid,
    dedupe_hash        varchar(64),
    created_by         integer REFERENCES users(user_id),
    created_at         timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_bank_statement_dedupe
  ON bank_statement_lines(bank_account_id, dedupe_hash);
CREATE INDEX IF NOT EXISTS ix_bank_statement_account_status
  ON bank_statement_lines(bank_account_id, status);
CREATE INDEX IF NOT EXISTS ix_bank_statement_date
  ON bank_statement_lines(bank_account_id, statement_date);

-- E1.2 — reconciliation runs (the review container)
CREATE TABLE IF NOT EXISTS bank_reconciliation_runs (
    run_id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_no             varchar(30) NOT NULL,
    bank_account_id    integer NOT NULL REFERENCES cash_accounts(cash_account_id),
    branch_id          integer NOT NULL REFERENCES branches(branch_id),
    period_id          integer REFERENCES periods(period_id),
    run_date           date NOT NULL,
    book_balance       numeric(18,2) NOT NULL,
    statement_balance  numeric(18,2) NOT NULL,
    variance           numeric(18,2) NOT NULL,
    matched_count      integer NOT NULL DEFAULT 0,
    unmatched_count    integer NOT NULL DEFAULT 0,
    -- 1 draft · 2 posted · 3 reversed
    status             smallint NOT NULL DEFAULT 1,
    journal_id         bigint REFERENCES gl_journals(journal_id),
    reverse_journal_id bigint REFERENCES gl_journals(journal_id),
    reversal_of        bigint REFERENCES bank_reconciliation_runs(run_id),
    notes              text,
    created_by         integer NOT NULL REFERENCES users(user_id),
    posted_by          integer REFERENCES users(user_id),
    posted_at          timestamptz,
    created_at         timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_bank_recon_run_no ON bank_reconciliation_runs(run_no);
CREATE INDEX IF NOT EXISTS ix_bank_recon_branch_date ON bank_reconciliation_runs(branch_id, run_date);

-- E1.3 — which lines a run covers (and which journal adjusted them)
CREATE TABLE IF NOT EXISTS bank_reconciliation_run_lines (
    run_id               bigint NOT NULL REFERENCES bank_reconciliation_runs(run_id) ON DELETE CASCADE,
    line_id              bigint NOT NULL REFERENCES bank_statement_lines(line_id),
    adjustment_journal_id bigint REFERENCES gl_journals(journal_id),
    PRIMARY KEY (run_id, line_id)
);

-- E1.4 — auto-matching rules (pattern on description, fee mapping hint)
CREATE TABLE IF NOT EXISTS bank_matching_rules (
    rule_id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id          integer NOT NULL REFERENCES branches(branch_id),
    pattern            text NOT NULL,
    movement_type      smallint NOT NULL DEFAULT 1,
    counterparty_hint  text,
    gl_account_id      integer REFERENCES gl_accounts(account_id),
    tolerance_amount   numeric(18,2) NOT NULL DEFAULT 0,
    priority           integer NOT NULL DEFAULT 10,
    is_active          boolean NOT NULL DEFAULT true,
    created_at         timestamptz NOT NULL DEFAULT now()
);

-- E1.5 — bank cash account gets reconciliation bookkeeping
ALTER TABLE cash_accounts
    ADD COLUMN IF NOT EXISTS reconciled_balance numeric(18,2),
    ADD COLUMN IF NOT EXISTS last_reconciled_at timestamptz;

