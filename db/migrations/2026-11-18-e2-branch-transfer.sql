-- E2 — Inter-branch (cross-branch) stock transfer.
-- Additive only: two new tables, one new clearing account (1108) and one
-- new mapping key. The same-branch transfer flow (stock_transfers) is
-- untouched.
--
-- Accounting policy (approved):
--   at issue     (approve): Dr 1108 / Cr 1104   in the SOURCE branch
--   at receipt   (receive): Dr 1104 / Cr 1108   in the DESTINATION branch
--   the balance of 1108 is the exact value of goods in transit between
--   branches and must reach ZERO once every issued transfer is received.
--   Company-wide totals (assets, liabilities, equity, P&L) are unaffected.

CREATE TABLE IF NOT EXISTS branch_transfers (
    branch_transfer_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_no         varchar(60) NOT NULL UNIQUE,
    transfer_date       date NOT NULL DEFAULT CURRENT_DATE,
    from_branch_id      integer NOT NULL REFERENCES branches(branch_id),
    to_branch_id        integer NOT NULL REFERENCES branches(branch_id),
    from_warehouse_id   integer NOT NULL REFERENCES warehouses(warehouse_id),
    to_warehouse_id     integer NOT NULL REFERENCES warehouses(warehouse_id),
    -- 1 draft · 2 approved/issued (outbound) · 4 received/completed · 5 cancelled
    status              smallint NOT NULL DEFAULT 1,
    total_value         numeric(18,2) NOT NULL DEFAULT 0,
    notes               text,
    client_request_id   varchar(64),
    outbound_voucher_id bigint REFERENCES stock_vouchers(stock_voucher_id),
    inbound_voucher_id  bigint REFERENCES stock_vouchers(stock_voucher_id),
    outbound_journal_id bigint REFERENCES gl_journals(journal_id),
    inbound_journal_id  bigint REFERENCES gl_journals(journal_id),
    created_by          integer NOT NULL REFERENCES users(user_id),
    approved_by         integer REFERENCES users(user_id),
    approved_at         timestamptz,
    received_at         timestamptz,
    cancelled_by        integer REFERENCES users(user_id),
    cancelled_at        timestamptz,
    cancel_reason       text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT chk_branch_transfers_distinct_branches CHECK (from_branch_id <> to_branch_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_branch_transfers_client_request
    ON branch_transfers(client_request_id) WHERE client_request_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_branch_transfers_from ON branch_transfers(from_branch_id, status);
CREATE INDEX IF NOT EXISTS ix_branch_transfers_to   ON branch_transfers(to_branch_id,   status);
CREATE INDEX IF NOT EXISTS ix_branch_transfers_date ON branch_transfers(transfer_date);

CREATE TABLE IF NOT EXISTS branch_transfer_lines (
    line_id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_transfer_id  bigint NOT NULL REFERENCES branch_transfers(branch_transfer_id) ON DELETE CASCADE,
    line_number         integer NOT NULL,
    item_id             integer NOT NULL REFERENCES items(item_id),
    unit_id             integer NOT NULL REFERENCES units(unit_id),
    quantity            numeric(18,6) NOT NULL,
    unit_cost           numeric(18,4) NOT NULL DEFAULT 0,
    serial_no           varchar(100),
    expiry_date         date,
    notes               text,
    UNIQUE (branch_transfer_id, line_number)
);

