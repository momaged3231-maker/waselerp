-- ------------------------------------------------------------------ --
--  Salary components (allowances / deductions)
-- ------------------------------------------------------------------ --
CREATE TABLE IF NOT EXISTS salary_components (
    component_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           varchar(200) NOT NULL,
    -- 1 allowance, 2 deduction, 3 employer contribution
    component_type smallint NOT NULL DEFAULT 1,
    -- 1 fixed amount, 2 percentage of the basic salary
    calc_type      smallint NOT NULL DEFAULT 1,
    amount         numeric(18,4) NOT NULL DEFAULT 0,
    is_active      boolean NOT NULL DEFAULT true,
    notes          text,
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_salary_components_name ON salary_components(name);

CREATE TABLE IF NOT EXISTS employee_salary_components (
    employee_component_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id    integer NOT NULL REFERENCES employees(employee_id) ON DELETE CASCADE,
    component_id   integer NOT NULL REFERENCES salary_components(component_id) ON DELETE CASCADE,
    amount_override numeric(18,4),
    is_active      boolean NOT NULL DEFAULT true,
    UNIQUE (employee_id, component_id)
);
CREATE INDEX IF NOT EXISTS ix_employee_components_employee ON employee_salary_components(employee_id);

CREATE TABLE IF NOT EXISTS salary_pay_lines (
    salary_pay_line_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    salary_pay_id  bigint NOT NULL REFERENCES salary_pays(salary_pay_id) ON DELETE CASCADE,
    component_id   integer REFERENCES salary_components(component_id),
    name           varchar(200) NOT NULL,
    -- 1 earning, 2 deduction
    line_type      smallint NOT NULL DEFAULT 1,
    amount         numeric(18,2) NOT NULL DEFAULT 0,
    sort_order     integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS ix_salary_pay_lines_pay ON salary_pay_lines(salary_pay_id);

-- ------------------------------------------------------------------ --
--  Employee advances (loans repaid by monthly deductions)
-- ------------------------------------------------------------------ --
CREATE TABLE IF NOT EXISTS employee_advances (
    advance_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id    integer NOT NULL REFERENCES employees(employee_id),
    branch_id      integer NOT NULL REFERENCES branches(branch_id),
    advance_date   date NOT NULL DEFAULT CURRENT_DATE,
    amount         numeric(18,2) NOT NULL DEFAULT 0,
    monthly_deduction numeric(18,2) NOT NULL DEFAULT 0,
    deducted_amount numeric(18,2) NOT NULL DEFAULT 0,
    -- 1 open, 2 closed, 3 cancelled
    status         smallint NOT NULL DEFAULT 1,
    cash_account_id integer REFERENCES cash_accounts(cash_account_id),
    gl_journal_id  bigint REFERENCES gl_journals(journal_id),
    notes          text,
    created_by     integer REFERENCES users(user_id),
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_employee_advances_employee ON employee_advances(employee_id, status);

CREATE TABLE IF NOT EXISTS advance_deductions (
    deduction_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advance_id     bigint NOT NULL REFERENCES employee_advances(advance_id) ON DELETE CASCADE,
    salary_pay_id  bigint REFERENCES salary_pays(salary_pay_id) ON DELETE CASCADE,
    amount         numeric(18,2) NOT NULL DEFAULT 0,
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_advance_deductions_advance ON advance_deductions(advance_id);

