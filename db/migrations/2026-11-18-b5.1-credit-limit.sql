-- B5.1 — Credit limit + overdue (DEC-SALES-001..008, DEC-SALES-005).
--
-- Design decisions (owner, 2026-11-18):
--  Q1 PDC: exposure-only correction. GL check posting stays as-is (TD-37).
--    ledger_balance already drops when a PDC is received (Cr AR at receipt,
--    accounting.slice.ts:743-751), so uncollected PDC is ADDED BACK to exposure
--    until collectCheck flips status away from 1. No GL change here.
--  Q2 installments: EXCLUDED from exposure in B5.1 (TD-38). A reserved column
--    documents the intent; filled when installments get a full GL.
--  credit_unlimited: explicit boolean; 0 / NULL limit = block all credit sales
--    (DEC-SALES-005), never treated as "unlimited" (which was the old bug).

-- grace_days: per customer (DEC-SALES-003), default 0.
ALTER TABLE parties ADD COLUMN IF NOT EXISTS grace_days integer NOT NULL DEFAULT 0 CHECK (grace_days >= 0);
-- explicit unlimited flag (DEC-SALES-005)
ALTER TABLE parties ADD COLUMN IF NOT EXISTS credit_unlimited boolean NOT NULL DEFAULT false;

-- override audit table (DEC-SALES-001 / B5.1c)
CREATE TABLE IF NOT EXISTS sales_credit_overrides (
  override_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id    bigint NULL REFERENCES invoices(invoice_id),
  party_id      integer NOT NULL REFERENCES parties(party_id),
  branch_id     integer NOT NULL REFERENCES branches(branch_id),
  exposure      numeric(18,2) NOT NULL,
  credit_limit  numeric(18,2) NOT NULL,
  excess        numeric(18,2) NOT NULL,
  was_overdue   boolean NOT NULL,
  overridden_by integer NOT NULL REFERENCES users(user_id),
  reason        text NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_sco_party   ON sales_credit_overrides(party_id);
CREATE INDEX IF NOT EXISTS ix_sco_created ON sales_credit_overrides(created_at);

-- Single source of truth for customer credit exposure (DEC-SALES-008 pattern).
-- checks.status = 1 is "under collection" (verified against live test DB).
CREATE OR REPLACE VIEW v_customer_exposure AS
SELECT
  p.party_id,
  p.credit_limit,
  p.credit_unlimited,
  p.grace_days,
  COALESCE((
    SELECT SUM(CASE WHEN l.direction = 1 THEN l.amount ELSE -l.amount END)
    FROM ledger_entries l WHERE l.party_id = p.party_id
  ), p.opening_balance, 0) AS ledger_balance,
  COALESCE((
    SELECT SUM(c.amount) FROM checks c
    WHERE c.party_id = p.party_id AND c.direction = 1 AND c.status = 1
  ), 0) AS uncollected_pdc,
  0::numeric(18,2) AS installment_exposure,  -- TD-38: reserved, excluded in B5.1
  (COALESCE((
    SELECT SUM(CASE WHEN l.direction = 1 THEN l.amount ELSE -l.amount END)
    FROM ledger_entries l WHERE l.party_id = p.party_id
  ), p.opening_balance, 0)
  + COALESCE((
    SELECT SUM(c.amount) FROM checks c
    WHERE c.party_id = p.party_id AND c.direction = 1 AND c.status = 1
  ), 0)) AS exposure
FROM parties p
WHERE p.party_type = 1;  -- customers only
