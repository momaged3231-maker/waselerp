/* P7.5 — countries, cities and shipping methods/rates. */
CREATE TABLE IF NOT EXISTS countries (
    country_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(10) NOT NULL UNIQUE,
    name varchar(200) NOT NULL,
    name_en varchar(200),
    is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS cities (
    city_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id integer NOT NULL REFERENCES countries(country_id),
    name varchar(200) NOT NULL,
    name_en varchar(200),
    is_active boolean NOT NULL DEFAULT true
);
CREATE INDEX IF NOT EXISTS ix_cities_country ON cities(country_id);
CREATE TABLE IF NOT EXISTS shipping_methods (
    shipping_method_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(50) NOT NULL UNIQUE,
    name varchar(200) NOT NULL,
    is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS shipping_rates (
    shipping_rate_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipping_method_id integer NOT NULL REFERENCES shipping_methods(shipping_method_id),
    from_city_id integer NOT NULL REFERENCES cities(city_id),
    to_city_id integer NOT NULL REFERENCES cities(city_id),
    rate numeric(18,4) NOT NULL DEFAULT 0,
    estimated_days integer,
    is_active boolean NOT NULL DEFAULT true,
    UNIQUE (shipping_method_id, from_city_id, to_city_id)
);
CREATE INDEX IF NOT EXISTS ix_shipping_rates_route ON shipping_rates(from_city_id, to_city_id);