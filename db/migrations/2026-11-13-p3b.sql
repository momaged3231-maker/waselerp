/* P3 (part 2) — restaurant halls, service charge modes, modifiers, notes.
   Run after db/schema.postgres.sql on a database created before P3b. */

CREATE TABLE IF NOT EXISTS restaurant_settings (
    settings_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer NOT NULL REFERENCES branches(branch_id),
    service_charge_per_guest numeric(18,2) NOT NULL DEFAULT 0,
    service_charge_minimum numeric(18,2) NOT NULL DEFAULT 0,
    service_charge_mode smallint NOT NULL DEFAULT 1,
    service_charge_account_id integer REFERENCES gl_accounts(account_id),
    kitchen_columns jsonb NOT NULL DEFAULT '[]'::jsonb,
    notes text,
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (branch_id)
);
ALTER TABLE restaurant_settings ADD COLUMN IF NOT EXISTS service_charge_mode smallint NOT NULL DEFAULT 1;

CREATE TABLE IF NOT EXISTS restaurant_halls (
    hall_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer NOT NULL REFERENCES branches(branch_id),
    name varchar(100) NOT NULL,
    code varchar(10) NOT NULL,
    table_count integer NOT NULL DEFAULT 10,
    user_ids integer[] NOT NULL DEFAULT '{}',
    is_active boolean NOT NULL DEFAULT true,
    notes text,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (branch_id, name),
    UNIQUE (branch_id, code)
);

ALTER TABLE restaurant_tables ADD COLUMN IF NOT EXISTS hall_id integer REFERENCES restaurant_halls(hall_id) ON DELETE CASCADE;
ALTER TABLE branches ADD COLUMN IF NOT EXISTS operating_mode smallint NOT NULL DEFAULT 1;

ALTER TABLE item_modifiers ADD COLUMN IF NOT EXISTS max_quantity numeric(18,6) NOT NULL DEFAULT 0;
ALTER TABLE item_modifiers ADD COLUMN IF NOT EXISTS sort_order integer NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS note_templates (
    note_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer REFERENCES branches(branch_id),
    name varchar(200) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE invoice_lines ADD COLUMN IF NOT EXISTS parent_line_id bigint REFERENCES invoice_lines(invoice_line_id);
ALTER TABLE invoice_lines ADD COLUMN IF NOT EXISTS is_modifier boolean NOT NULL DEFAULT false;

