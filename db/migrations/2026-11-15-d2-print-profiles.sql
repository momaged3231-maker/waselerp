-- D2: Station / print profiles — central, server-side print configuration.
-- Resolution order (web): selected profile → branch default profile → global app_settings.
-- A profile may leave the four "show" flags NULL to follow the global setting.

CREATE TABLE IF NOT EXISTS print_profiles (
    profile_id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id                integer NOT NULL REFERENCES branches(branch_id) ON DELETE CASCADE,
    name                     text NOT NULL,
    code                     text,
    default_printer          text,
    paper_size               text NOT NULL DEFAULT 'thermal80',
    receipt_copies           integer NOT NULL DEFAULT 1,
    auto_open_drawer         boolean NOT NULL DEFAULT true,
    receipt_width            integer NOT NULL DEFAULT 42,
    kitchen_ticket_enabled   boolean NOT NULL DEFAULT false,
    kitchen_ticket_copies    integer NOT NULL DEFAULT 1,
    kitchen_printer_name     text,
    show_tax_on_receipt      boolean,
    receipt_show_branch_name boolean,
    receipt_show_party_name  boolean,
    receipt_show_totals      boolean,
    is_default               boolean NOT NULL DEFAULT false,
    created_at               timestamptz NOT NULL DEFAULT now()
);

-- One profile name per branch.
CREATE UNIQUE INDEX IF NOT EXISTS ux_print_profiles_branch_name
    ON print_profiles (branch_id, lower(name));

-- At most one default profile per branch.
CREATE UNIQUE INDEX IF NOT EXISTS ux_print_profiles_branch_default
    ON print_profiles (branch_id) WHERE is_default;
