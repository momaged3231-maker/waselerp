ALTER TABLE items           ADD COLUMN IF NOT EXISTS gl_inventory_account_id integer REFERENCES gl_accounts(account_id);
ALTER TABLE items           ADD COLUMN IF NOT EXISTS gl_revenue_account_id integer REFERENCES gl_accounts(account_id);
ALTER TABLE items           ADD COLUMN IF NOT EXISTS gl_cogs_account_id integer REFERENCES gl_accounts(account_id);
ALTER TABLE parties         ADD COLUMN IF NOT EXISTS gl_account_id integer REFERENCES gl_accounts(account_id);
ALTER TABLE invoices        ADD COLUMN IF NOT EXISTS gl_journal_id bigint REFERENCES gl_journals(journal_id);
CREATE INDEX IF NOT EXISTS ix_invoices_gl_journal ON invoices(gl_journal_id);

