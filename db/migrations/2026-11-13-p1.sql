/* P1 — general ledger.
   Creates the chart of accounts, journals, entries, vouchers, checks,
   cost centres and currencies on an existing database.

   The chart of accounts itself is seeded by `npm run db:seed`
   (apps/api/src/cli/seed.ts → seedChartOfAccounts). */

CREATE TABLE IF NOT EXISTS currencies (
    currency_code varchar(10) PRIMARY KEY,
    name          varchar(120) NOT NULL,
    symbol        varchar(20),
    is_base       boolean NOT NULL DEFAULT false,
    rate          numeric(18,8) NOT NULL DEFAULT 1,
    updated_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS cost_centers (
    cost_center_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          varchar(30) NOT NULL UNIQUE,
    name          varchar(200) NOT NULL,
    parent_id     integer REFERENCES cost_centers(cost_center_id),
    is_active     boolean NOT NULL DEFAULT true,
    notes         text,
    created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS gl_accounts (
    account_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          varchar(30) NOT NULL UNIQUE,
    name          varchar(200) NOT NULL,
    name_en       varchar(200),
    account_type  smallint NOT NULL,
    parent_id     integer REFERENCES gl_accounts(account_id),
    is_group      boolean NOT NULL DEFAULT false,
    is_active     boolean NOT NULL DEFAULT true,
    normal_side   smallint NOT NULL DEFAULT 1,
    currency_code varchar(10) NOT NULL DEFAULT 'EGP',
    require_cost_center boolean NOT NULL DEFAULT false,
    notes         text,
    created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_gl_accounts_parent ON gl_accounts(parent_id);
CREATE INDEX IF NOT EXISTS ix_gl_accounts_type ON gl_accounts(account_type);

CREATE TABLE IF NOT EXISTS gl_mappings (
    mapping_key   varchar(60) PRIMARY KEY,
    account_id    integer NOT NULL REFERENCES gl_accounts(account_id),
    description   varchar(200)
);

CREATE TABLE IF NOT EXISTS gl_journals (
    journal_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_no    varchar(60) NOT NULL,
    journal_date  date NOT NULL DEFAULT CURRENT_DATE,
    journal_type  smallint NOT NULL DEFAULT 1,
    branch_id     integer NOT NULL REFERENCES branches(branch_id),
    period_id     integer REFERENCES periods(period_id),
    description   text,
    status        smallint NOT NULL DEFAULT 2,
    source_type   varchar(40),
    source_id     bigint,
    currency_code varchar(10) NOT NULL DEFAULT 'EGP',
    exchange_rate numeric(18,8) NOT NULL DEFAULT 1,
    total_debit   numeric(18,2) NOT NULL DEFAULT 0,
    total_credit  numeric(18,2) NOT NULL DEFAULT 0,
    created_by    integer REFERENCES users(user_id),
    posted_at     timestamptz,
    created_at    timestamptz NOT NULL DEFAULT now(),
    UNIQUE (branch_id, journal_no)
);
CREATE INDEX IF NOT EXISTS ix_gl_journals_date ON gl_journals(journal_date);
CREATE INDEX IF NOT EXISTS ix_gl_journals_status ON gl_journals(status);
CREATE INDEX IF NOT EXISTS ix_gl_journals_source ON gl_journals(source_type, source_id);

CREATE TABLE IF NOT EXISTS gl_entries (
    entry_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_id    bigint NOT NULL REFERENCES gl_journals(journal_id) ON DELETE CASCADE,
    line_no       integer NOT NULL,
    account_id    integer NOT NULL REFERENCES gl_accounts(account_id),
    debit         numeric(18,2) NOT NULL DEFAULT 0,
    credit        numeric(18,2) NOT NULL DEFAULT 0,
    description   text,
    cost_center_id integer REFERENCES cost_centers(cost_center_id),
    party_id      integer REFERENCES parties(party_id),
    branch_id     integer NOT NULL REFERENCES branches(branch_id),
    currency_code varchar(10) NOT NULL DEFAULT 'EGP',
    foreign_amount numeric(18,2) NOT NULL DEFAULT 0,
    exchange_rate numeric(18,8) NOT NULL DEFAULT 1,
    created_at    timestamptz NOT NULL DEFAULT now(),
    CHECK (debit >= 0 AND credit >= 0),
    CHECK (NOT (debit > 0 AND credit > 0))
);
CREATE INDEX IF NOT EXISTS ix_gl_entries_journal ON gl_entries(journal_id);
CREATE INDEX IF NOT EXISTS ix_gl_entries_account ON gl_entries(account_id);
CREATE INDEX IF NOT EXISTS ix_gl_entries_party ON gl_entries(party_id);

CREATE TABLE IF NOT EXISTS vouchers (
    voucher_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_no    varchar(60) NOT NULL,
    voucher_type  smallint NOT NULL,
    voucher_date  date NOT NULL DEFAULT CURRENT_DATE,
    branch_id     integer NOT NULL REFERENCES branches(branch_id),
    party_id      integer REFERENCES parties(party_id),
    cash_account_id integer REFERENCES cash_accounts(cash_account_id),
    payment_method smallint NOT NULL DEFAULT 1,
    amount        numeric(18,2) NOT NULL CHECK (amount > 0),
    description   text,
    journal_id    bigint REFERENCES gl_journals(journal_id),
    status        smallint NOT NULL DEFAULT 1,
    created_by    integer REFERENCES users(user_id),
    created_at    timestamptz NOT NULL DEFAULT now(),
    UNIQUE (branch_id, voucher_no)
);
CREATE INDEX IF NOT EXISTS ix_vouchers_date ON vouchers(voucher_date);
CREATE INDEX IF NOT EXISTS ix_vouchers_party ON vouchers(party_id);

CREATE TABLE IF NOT EXISTS checks (
    check_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id     integer NOT NULL REFERENCES branches(branch_id),
    direction     smallint NOT NULL,
    check_no      varchar(60) NOT NULL,
    bank_name     varchar(200),
    amount        numeric(18,2) NOT NULL CHECK (amount > 0),
    due_date      date,
    party_id      integer REFERENCES parties(party_id),
    voucher_id    bigint REFERENCES vouchers(voucher_id),
    cash_account_id integer REFERENCES cash_accounts(cash_account_id),
    status        smallint NOT NULL DEFAULT 1,
    notes         text,
    created_by    integer REFERENCES users(user_id),
    created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_checks_status ON checks(status);
CREATE INDEX IF NOT EXISTS ix_checks_party ON checks(party_id);

CREATE TABLE IF NOT EXISTS recurring_journals (
    recurring_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(200) NOT NULL,
    description text,
    frequency   smallint NOT NULL DEFAULT 1,
    day_of_month smallint NOT NULL DEFAULT 1,
    next_date   date,
    branch_id   integer NOT NULL REFERENCES branches(branch_id),
    is_active   boolean NOT NULL DEFAULT true,
    created_by  integer REFERENCES users(user_id),
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS recurring_journal_lines (
    recurring_line_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recurring_id integer NOT NULL REFERENCES recurring_journals(recurring_id) ON DELETE CASCADE,
    line_no      integer NOT NULL,
    account_id   integer NOT NULL REFERENCES gl_accounts(account_id),
    debit        numeric(18,2) NOT NULL DEFAULT 0,
    credit       numeric(18,2) NOT NULL DEFAULT 0,
    description  text,
    cost_center_id integer REFERENCES cost_centers(cost_center_id)
);
CREATE INDEX IF NOT EXISTS ix_recurring_lines_recurring ON recurring_journal_lines(recurring_id);

