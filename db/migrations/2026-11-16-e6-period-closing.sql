-- E6 — Automated period closing (الإقفال الشهري الآلي)
-- Accounting impact: revenue/expense accounts are zeroed into RETAINED_EARNINGS (3103)
-- via ONE balanced journal per closing (source_type = 'period_close', source_id = period_id).
-- No history is rewritten; the closing entry is a reversible accounting document.

ALTER TABLE periods
    ADD COLUMN IF NOT EXISTS closing_entry_id bigint REFERENCES gl_journals(journal_id),
    ADD COLUMN IF NOT EXISTS net_income numeric(18,2);

-- Persistent record of every pre-close check run against a period.
CREATE TABLE IF NOT EXISTS period_close_checks (
    check_id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_id          integer NOT NULL REFERENCES periods(period_id) ON DELETE CASCADE,
    branch_id          integer NOT NULL REFERENCES branches(branch_id),
    check_code         varchar(60) NOT NULL,
    check_label        text NOT NULL,
    -- 1 pending · 2 passed · 3 failed · 4 bypassed
    status             smallint NOT NULL DEFAULT 1,
    details            text,
    checked_at         timestamptz,
    resolved_by        integer REFERENCES users(user_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_period_close_checks_period_code
    ON period_close_checks(period_id, check_code);
CREATE INDEX IF NOT EXISTS ix_period_close_checks_period
    ON period_close_checks(period_id);
