-- E3 — Auto Bank Expenses (الرسوم والعمولات البنكية الآلية)
-- Deterministic, idempotent generation of recurring bank fee journals.
-- Every journal still goes through common/posting.ts (source_type = 'bank_expense').
-- Each occurrence is registered in bank_expense_runs with UNIQUE(rule_id, period_key).

CREATE TABLE IF NOT EXISTS bank_expense_rules (
    rule_id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id           integer NOT NULL REFERENCES branches(branch_id),
    name                text NOT NULL,
    description         text,
    bank_account_id     integer NOT NULL REFERENCES cash_accounts(cash_account_id),
    expense_account_id  integer NOT NULL REFERENCES gl_accounts(account_id),
    amount              numeric(18,2) NOT NULL CHECK (amount > 0),
    -- 1 monthly · 2 quarterly · 3 semi-annual · 4 annual
    frequency           smallint NOT NULL DEFAULT 1,
    day_of_month        smallint NOT NULL CHECK (day_of_month BETWEEN 1 AND 28),
    start_date          date NOT NULL,
    end_date            date,
    counterparty_name   text,
    is_active           boolean NOT NULL DEFAULT true,
    suspended_at        timestamptz,
    suspended_reason    text,
    created_by          integer REFERENCES users(user_id),
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_bank_expense_rules_branch ON bank_expense_rules(branch_id, is_active);
CREATE INDEX IF NOT EXISTS ix_bank_expense_rules_day ON bank_expense_rules(day_of_month) WHERE is_active = true;

CREATE TABLE IF NOT EXISTS bank_expense_runs (
    run_id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id             integer NOT NULL REFERENCES bank_expense_rules(rule_id),
    period_key          date NOT NULL,              -- occurrence date (YYYY-MM-DD)
    -- 1 posted · 2 refused (e.g. closed period) · 3 reversed
    status              smallint NOT NULL DEFAULT 1,
    journal_id          bigint REFERENCES gl_journals(journal_id),
    refusal_reason      text,
    notes               text,
    created_by          integer REFERENCES users(user_id),
    run_at              timestamptz NOT NULL DEFAULT now()
);
-- Hard guarantee against double generation of the same occurrence.
CREATE UNIQUE INDEX IF NOT EXISTS ux_bank_expense_runs_rule_period ON bank_expense_runs(rule_id, period_key);
CREATE INDEX IF NOT EXISTS ix_bank_expense_runs_journal ON bank_expense_runs(journal_id);
CREATE INDEX IF NOT EXISTS ix_bank_expense_runs_rule ON bank_expense_runs(rule_id);
