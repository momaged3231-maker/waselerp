/* P4 — stock count document (سند الجرد).
   A counting document that stays a draft while the warehouse is counted and
   is applied to the stock only when it is approved. */

CREATE TABLE IF NOT EXISTS stock_counts (
    stock_count_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    count_no varchar(60) NOT NULL,
    count_date date NOT NULL DEFAULT CURRENT_DATE,
    branch_id integer NOT NULL REFERENCES branches(branch_id),
    warehouse_id integer NOT NULL REFERENCES warehouses(warehouse_id),
    employee_id integer NOT NULL REFERENCES employees(employee_id),
    notes text,
    status smallint NOT NULL DEFAULT 1,
    total_expected numeric(18,6) NOT NULL DEFAULT 0,
    total_counted numeric(18,6) NOT NULL DEFAULT 0,
    total_difference numeric(18,6) NOT NULL DEFAULT 0,
    total_value numeric(18,4) NOT NULL DEFAULT 0,
    gl_journal_id bigint REFERENCES gl_journals(journal_id),
    created_by integer NOT NULL REFERENCES users(user_id),
    approved_by integer REFERENCES users(user_id),
    approved_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (branch_id, count_no)
);
CREATE INDEX IF NOT EXISTS ix_stock_counts_warehouse ON stock_counts(warehouse_id, status);

CREATE TABLE IF NOT EXISTS stock_count_lines (
    stock_count_line_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_count_id bigint NOT NULL REFERENCES stock_counts(stock_count_id) ON DELETE CASCADE,
    line_number integer NOT NULL,
    item_id integer NOT NULL REFERENCES items(item_id),
    unit_id integer NOT NULL REFERENCES units(unit_id),
    counted_qty numeric(18,6) NOT NULL DEFAULT 0,
    expected_qty numeric(18,6) NOT NULL DEFAULT 0,
    difference_qty numeric(18,6) NOT NULL DEFAULT 0,
    unit_cost numeric(18,4) NOT NULL DEFAULT 0,
    expiry_date date,
    notes text
);
CREATE INDEX IF NOT EXISTS ix_stock_count_lines_count ON stock_count_lines(stock_count_id);

