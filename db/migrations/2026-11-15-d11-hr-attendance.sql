CREATE TABLE IF NOT EXISTS latency_deduction_tiers (
    tier_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer NOT NULL DEFAULT 0,      -- 0 = applies to all branches
    from_minutes integer NOT NULL,
    to_minutes integer,                         -- NULL = open-ended top tier
    percent numeric(6,2) NOT NULL DEFAULT 0,    -- % of the employee's day wage
    sort_order integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO latency_deduction_tiers (branch_id, from_minutes, to_minutes, percent, sort_order)
SELECT 0, 1, 15, 25, 1 WHERE NOT EXISTS (SELECT 1 FROM latency_deduction_tiers WHERE branch_id = 0 AND from_minutes = 1);
INSERT INTO latency_deduction_tiers (branch_id, from_minutes, to_minutes, percent, sort_order)
SELECT 0, 16, 30, 50, 2 WHERE NOT EXISTS (SELECT 1 FROM latency_deduction_tiers WHERE branch_id = 0 AND from_minutes = 16);
INSERT INTO latency_deduction_tiers (branch_id, from_minutes, to_minutes, percent, sort_order)
SELECT 0, 31, NULL, 100, 3 WHERE NOT EXISTS (SELECT 1 FROM latency_deduction_tiers WHERE branch_id = 0 AND from_minutes = 31);

CREATE TABLE IF NOT EXISTS early_permissions (
    permission_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer NOT NULL REFERENCES branches(branch_id),
    employee_id integer NOT NULL REFERENCES employees(employee_id),
    permission_date date NOT NULL,
    from_time time NOT NULL,
    to_time time NOT NULL,
    minutes integer NOT NULL,
    reason varchar(300),
    deduct_from_salary boolean NOT NULL DEFAULT false,
    status smallint NOT NULL DEFAULT 1,          -- 1 pending, 2 approved, 3 rejected
    notes text,
    created_by integer REFERENCES users(user_id),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (employee_id, permission_date)
);
CREATE INDEX IF NOT EXISTS ix_early_permissions_employee ON early_permissions(employee_id, permission_date);
