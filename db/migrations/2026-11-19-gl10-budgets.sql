-- GL-10 — Budgets (v1)
-- Additive only. No posting.ts change, no period coupling, base currency only.
--
-- VERIFIED BEFORE WRITING (PGlite 5434, 2026-11-19):
--   gl_entries columns  : entry_id, journal_id, line_no, account_id, debit, credit,
--                         description, cost_center_id, party_id, branch_id,
--                         currency_code, foreign_amount, exchange_rate, created_at
--                         >>> NO date column <<<
--   gl_journals columns : journal_id, journal_no, journal_date, journal_type, branch_id,
--                         period_id, description, status, source_type, source_id,
--                         currency_code, exchange_rate, total_debit, total_credit, ...
--                         status: 1=draft, 2=posted, 3=voided
--   gl_accounts columns : account_id, code, name, name_en, account_type, parent_id,
--                         is_group, is_active, is_control, normal_side, currency_code,
--                         require_cost_center, notes, created_at
--                         >>> column is `account_type`, NOT `type` <<<
--   currencies.is_base  : true for exactly one row (EGP on the test DB)
--
-- Therefore the actual-amount aggregation reads the date from gl_journals and
-- filters status = 2 (posted). Reversal journals are posted entries with
-- opposite signs, so they net to zero naturally — they are never excluded.

CREATE TABLE IF NOT EXISTS budgets (
  budget_id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch_id                 integer NOT NULL REFERENCES branches(branch_id),
  year                      integer NOT NULL CHECK (year BETWEEN 2020 AND 2100),
  name                      text NOT NULL,
  status                    smallint NOT NULL DEFAULT 1
                              CHECK (status IN (1, 2, 3, 4)),  -- 1 draft, 2 approved, 3 closed, 4 superseded
  currency_code             varchar(8) NOT NULL,
  created_by                integer NOT NULL REFERENCES users(user_id),
  approved_by               integer NULL REFERENCES users(user_id),
  approved_at               timestamptz NULL,
  same_user_approval_reason text NULL,
  closed_by                 integer NULL REFERENCES users(user_id),
  closed_at                 timestamptz NULL,
  superseded_by             bigint NULL REFERENCES budgets(budget_id),
  supersedes_id             bigint NULL REFERENCES budgets(budget_id),
  notes                     text,
  created_at                timestamptz NOT NULL DEFAULT now(),
  UNIQUE (branch_id, year, name)
);

CREATE INDEX IF NOT EXISTS ix_budgets_branch_year ON budgets(branch_id, year);
CREATE INDEX IF NOT EXISTS ix_budgets_status      ON budgets(status);
CREATE INDEX IF NOT EXISTS ix_budgets_supersedes  ON budgets(supersedes_id);

CREATE TABLE IF NOT EXISTS budget_lines (
  line_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  budget_id       bigint NOT NULL REFERENCES budgets(budget_id) ON DELETE CASCADE,
  account_id      integer NOT NULL REFERENCES gl_accounts(account_id),
  cost_center_id  integer NULL REFERENCES cost_centers(cost_center_id),
  period_month    smallint NOT NULL CHECK (period_month BETWEEN 1 AND 12),
  planned_amount  numeric(18,2) NOT NULL CHECK (planned_amount >= 0)
);

CREATE INDEX IF NOT EXISTS ix_bl_budget  ON budget_lines(budget_id);
CREATE INDEX IF NOT EXISTS ix_bl_account ON budget_lines(account_id);

-- A plain UNIQUE(...) does NOT stop duplicates when cost_center_id IS NULL
-- (NULLs are distinct in Postgres). Two partial unique indexes close that hole.
CREATE UNIQUE INDEX IF NOT EXISTS ux_bl_nocc
  ON budget_lines(budget_id, account_id, period_month)
  WHERE cost_center_id IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS ux_bl_cc
  ON budget_lines(budget_id, account_id, cost_center_id, period_month)
  WHERE cost_center_id IS NOT NULL;

-- Budget vs actual, one row per budget line.
--   Revenue  (account_type 4): actual = SUM(credit) - SUM(debit)
--   Expense  (account_type 5): actual = SUM(debit)  - SUM(credit)
--   is_group = true accounts are excluded from matching (their children carry
--   the postings; matching the parent would double count).

-- The aggregate subquery keeps raw debit/credit; the sign is applied here per
-- account type so callers cannot get the direction wrong.
--
-- COST CENTRE SEMANTICS (approved): a budget line with cost_center_id = NULL is
-- the "غير موزّع" bucket and matches ONLY entries that carry no cost centre.
-- It does NOT mean "all cost centres" — otherwise «موزّع + غير موزّع» would
-- exceed the branch total. The two buckets are disjoint and add up to the total:
--   SUM(actual of NULL lines) + SUM(actual of CC lines) = branch total.
-- Hence NULL-safe equality (IS NOT DISTINCT FROM) instead of an OR.
CREATE OR REPLACE VIEW v_budget_actual AS
SELECT
  bl.line_id,
  bl.budget_id,
  b.branch_id,
  b.year,
  bl.account_id,
  a.code                                          AS account_code,
  a.name                                          AS account_name,
  a.account_type,
  bl.cost_center_id,
  bl.period_month,
  bl.planned_amount,
  COALESCE(SUM(
    CASE
      WHEN a.account_type = 4 THEN agg.credit - agg.debit
      WHEN a.account_type = 5 THEN agg.debit  - agg.credit
      ELSE 0
    END
  ), 0)                                           AS actual_amount
FROM budget_lines bl
JOIN budgets     b ON b.budget_id  = bl.budget_id
JOIN gl_accounts a ON a.account_id = bl.account_id
LEFT JOIN (
  SELECT e.account_id,
         e.branch_id,
         e.cost_center_id,
         EXTRACT(YEAR  FROM j.journal_date)::int AS year,
         EXTRACT(MONTH FROM j.journal_date)::int AS period_month,
         SUM(e.debit)                            AS debit,
         SUM(e.credit)                           AS credit
    FROM gl_entries  e
    JOIN gl_journals j ON j.journal_id = e.journal_id
   WHERE j.status = 2
   GROUP BY e.account_id, e.branch_id, e.cost_center_id,
            EXTRACT(YEAR FROM j.journal_date), EXTRACT(MONTH FROM j.journal_date)
) agg ON agg.account_id  = bl.account_id
     AND agg.branch_id   = b.branch_id
     AND agg.year        = b.year
     AND agg.period_month = bl.period_month
     AND agg.cost_center_id IS NOT DISTINCT FROM bl.cost_center_id
WHERE a.is_group = false
  AND a.account_type IN (4, 5)
GROUP BY bl.line_id, bl.budget_id, b.branch_id, b.year, bl.account_id,
         a.code, a.name, a.account_type, bl.cost_center_id, bl.period_month,
         bl.planned_amount
;
