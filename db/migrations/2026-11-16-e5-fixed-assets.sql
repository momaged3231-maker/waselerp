-- E5 — Fixed Assets & Depreciation (الأصول الثابتة والإهلاك)
-- Isolated tables. All journals still go through common/posting.ts (source_type =
-- 'fixed_asset' | 'asset_depreciation' | 'asset_disposal' | 'reversal').
-- Lines are never deleted — permanent audit trail. Reversal via mirror journals.

CREATE TABLE IF NOT EXISTS fixed_assets (
    asset_id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_code             varchar(60) NOT NULL UNIQUE,
    name                   text NOT NULL,
    category               varchar(60) NOT NULL,
    branch_id              integer NOT NULL REFERENCES branches(branch_id),
    gl_asset_account_id    integer NOT NULL REFERENCES gl_accounts(account_id),
    gl_accumulated_account_id integer NOT NULL REFERENCES gl_accounts(account_id),
    cost                   numeric(18,2) NOT NULL CHECK (cost > 0),
    residual_value         numeric(18,2) NOT NULL DEFAULT 0,
    useful_life_months     integer NOT NULL CHECK (useful_life_months > 0),
    acquisition_date        date NOT NULL,
    in_service_date        date NOT NULL,
    depreciation_method    smallint NOT NULL DEFAULT 1,   -- 1 straight line · 2 diminishing balance
    depreciation_rate_pct  numeric(6,2),                 -- annual rate for diminishing balance
    expected_end_date      date,
    tag_number             varchar(60),
    responsible_person     text,
    supplier_id            integer REFERENCES parties(party_id),
    supplier_invoice_id    bigint REFERENCES invoices(invoice_id),
    status                 smallint NOT NULL DEFAULT 1,   -- 1 in-service · 2 idle · 3 sold · 4 disposed · 5 written-off
    gl_asset_journal_id    bigint REFERENCES gl_journals(journal_id),
    notes                  text,
    created_by             integer REFERENCES users(user_id),
    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_fixed_assets_branch_status ON fixed_assets(branch_id, status);
CREATE INDEX IF NOT EXISTS ix_fixed_assets_code ON fixed_assets(asset_code);

CREATE TABLE IF NOT EXISTS asset_depreciation_lines (
    line_id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id               integer NOT NULL REFERENCES fixed_assets(asset_id) ON DELETE CASCADE,
    period_month           date NOT NULL,                 -- 'YYYY-MM-01'
    depreciation_amount    numeric(18,2) NOT NULL,
    accumulated            numeric(18,2) NOT NULL,
    book_value             numeric(18,2) NOT NULL,
    journal_id             bigint REFERENCES gl_journals(journal_id),
    posted_at              timestamptz NOT NULL DEFAULT now()
);
-- One depreciation line per asset per month — hard guarantee against double posting.
CREATE UNIQUE INDEX IF NOT EXISTS ux_asset_dep_asset_month ON asset_depreciation_lines(asset_id, period_month);
CREATE INDEX IF NOT EXISTS ix_asset_dep_period ON asset_depreciation_lines(period_month);

CREATE TABLE IF NOT EXISTS asset_disposals (
    disposal_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id               integer NOT NULL REFERENCES fixed_assets(asset_id),
    disposal_date          date NOT NULL,
    disposal_type          smallint NOT NULL DEFAULT 1,   -- 1 sale · 4 write-off (هلاك/تفريخ)
    disposal_amount        numeric(18,2) NOT NULL DEFAULT 0,
    cost_basis             numeric(18,2) NOT NULL,
    accumulated_basis      numeric(18,2) NOT NULL,
    book_value_basis       numeric(18,2) NOT NULL,
    gain_loss              numeric(18,2) NOT NULL DEFAULT 0,
    gl_journal_id          bigint REFERENCES gl_journals(journal_id),
    reverse_journal_id     bigint REFERENCES gl_journals(journal_id),
    reason                 text,
    created_by             integer REFERENCES users(user_id),
    created_at             timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_asset_disposals_asset ON asset_disposals(asset_id);
