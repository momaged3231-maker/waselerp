-- P8 — Maintenance Centers (إدارة مراكز الصيانة) [docs/ezees-guide/maintenance-centers.txt]
-- Service orders for device-repair shops: intake -> inspection -> parts ->
-- delivery/payment, advance payments posted to the ledger on intake.
-- Additive migration: safe to run on an initialised database.
-- ============================================================================

-- ---------- Reference data ----------

CREATE TABLE IF NOT EXISTS maintenance_products (
    product_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL UNIQUE,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS maintenance_models (
    model_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id integer NOT NULL REFERENCES maintenance_products(product_id) ON DELETE CASCADE,
    name varchar(120) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (product_id, name)
);

CREATE TABLE IF NOT EXISTS fault_categories (
    fault_category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL UNIQUE,
    sort_order integer NOT NULL DEFAULT 0,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS fault_subcategories (
    fault_subcategory_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fault_category_id integer NOT NULL REFERENCES fault_categories(fault_category_id) ON DELETE CASCADE,
    name varchar(200) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (fault_category_id, name)
);

-- ---------- Service orders (إذن صيانة) ----------

CREATE TABLE IF NOT EXISTS maintenance_tickets (
    ticket_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer NOT NULL REFERENCES branches(branch_id),
    branch_cash_account_id integer REFERENCES cash_accounts(cash_account_id),
    ticket_no varchar(40) NOT NULL,
    -- Customer is stored on the ticket, NOT in the parties/customers table.
    customer_name varchar(200) NOT NULL,
    phone varchar(40) NOT NULL,
    phone2 varchar(40),
    product_id integer NOT NULL REFERENCES maintenance_products(product_id),
    model_id integer NOT NULL REFERENCES maintenance_models(model_id),
    serial_no varchar(120),
    item_color varchar(80),
    accessories jsonb NOT NULL DEFAULT '{}'::jsonb,
    product_condition text NOT NULL,
    customer_notes text,
    max_charge numeric(14,2) NOT NULL DEFAULT 0,
    received_at timestamptz NOT NULL DEFAULT now(),
    expected_delivery date,
    estimated_cost numeric(14,2) NOT NULL DEFAULT 0,
    actual_cost numeric(14,2),
    total_paid numeric(14,2) NOT NULL DEFAULT 0,
    advance_posted boolean NOT NULL DEFAULT false,
    advance_journal_id integer,
    payment_journal_id integer,
    advance_amount numeric(14,2) NOT NULL DEFAULT 0,
    last_payment_amount numeric(14,2) NOT NULL DEFAULT 0,
    inspection_status smallint NOT NULL DEFAULT 0, -- 0 waiting, 1 under check, 2 refused, 3 repaired, 4 returned
    delivery_status smallint NOT NULL DEFAULT 0,   -- 0 not delivered, 1 delivered
    check_report text,
    engineer_id integer REFERENCES users(user_id),
    created_by integer REFERENCES users(user_id),
    delivered_by integer REFERENCES users(user_id),
    delivered_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (branch_id, ticket_no)
);
CREATE INDEX IF NOT EXISTS maintenance_tickets_branch_idx ON maintenance_tickets (branch_id, received_at DESC);
CREATE INDEX IF NOT EXISTS maintenance_tickets_status_idx ON maintenance_tickets (branch_id, inspection_status, delivery_status);

-- ---------- Spare parts consumed by a ticket (تُخصم عند حفظ الفحص) ----------

CREATE TABLE IF NOT EXISTS maintenance_ticket_parts (
    ticket_part_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id integer NOT NULL REFERENCES maintenance_tickets(ticket_id) ON DELETE CASCADE,
    item_id integer NOT NULL REFERENCES items(item_id),
    quantity numeric(14,3) NOT NULL,
    unit_price numeric(14,2) NOT NULL DEFAULT 0,
    unit_cost numeric(14,2) NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (ticket_id, item_id)
);
CREATE INDEX IF NOT EXISTS maintenance_ticket_parts_ticket_idx ON maintenance_ticket_parts (ticket_id);

-- ---------- Permissions ----------

INSERT INTO permissions (code, module, name) VALUES
  ('maintenance.view',   'الصيانة', 'عرض أذون الصيانة والتقارير'),
  ('maintenance.manage', 'الصيانة', 'استلام وفحص وتسليم وتعديل وحذف أذون الصيانة')
ON CONFLICT (code) DO NOTHING;

-- Grant the new permissions to every role that has full access (administrators).
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.role_id, p.permission_id
  FROM roles r
  JOIN permissions p ON p.code IN ('maintenance.view', 'maintenance.manage')
 WHERE r.name_en = 'Administrator'
ON CONFLICT DO NOTHING;
