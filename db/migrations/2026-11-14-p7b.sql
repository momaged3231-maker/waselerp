/* P7.2 — attachments (مرفقات) for business documents. */
CREATE TABLE IF NOT EXISTS attachments (
    attachment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer NOT NULL REFERENCES branches(branch_id),
    entity_type varchar(40) NOT NULL,
    entity_id bigint NOT NULL,
    file_name varchar(255) NOT NULL,
    mime_type varchar(120),
    file_size integer NOT NULL DEFAULT 0,
    content bytea NOT NULL,
    uploaded_by integer NOT NULL REFERENCES users(user_id),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (branch_id, entity_type, entity_id, file_name)
);
CREATE INDEX IF NOT EXISTS ix_attachments_entity
  ON attachments(branch_id, entity_type, entity_id);
