-- =====================================================================
--  WaselERP — PostgreSQL schema (central multi-branch ERP/POS)
--  Modular monolith, vertical slices, one central database.
--  Every transactional row carries branch_id so branches are logical
--  partitions of one store, not separate databases.
-- =====================================================================

CREATE TABLE IF NOT EXISTS branches (
    branch_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          varchar(30)  NOT NULL UNIQUE,
    name          varchar(200) NOT NULL,
    name_en       varchar(200),
    address       text,
    city          varchar(100),
    phone         varchar(40),
    tax_number    varchar(60),
    is_active     boolean NOT NULL DEFAULT true,
    notes         text,
    created_at    timestamptz NOT NULL DEFAULT now(),
    version       integer NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS users (
    user_id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name          varchar(100) NOT NULL UNIQUE,
    full_name          varchar(200) NOT NULL,
    password_hash      varchar(256) NOT NULL,
    password_salt      varchar(128) NOT NULL,
    default_branch_id  integer REFERENCES branches(branch_id),
    max_discount_pct   numeric(9,4) NOT NULL DEFAULT 0,
    email              varchar(200),
    phone              varchar(50),
    is_active          boolean NOT NULL DEFAULT true,
    is_cashier         boolean NOT NULL DEFAULT false,
    is_sales_rep       boolean NOT NULL DEFAULT false,
    commission_pct     numeric(9,4) NOT NULL DEFAULT 0,
    last_login_at      timestamptz,
    created_at         timestamptz NOT NULL DEFAULT now(),
    version            integer NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS roles (
    role_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      varchar(100) NOT NULL UNIQUE,
    name_en   varchar(100),
    is_system boolean NOT NULL DEFAULT false,
    notes     text
);

CREATE TABLE IF NOT EXISTS permissions (
    permission_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          varchar(120) NOT NULL UNIQUE,
    module        varchar(60)  NOT NULL,
    name          varchar(200) NOT NULL,
    description   text
);

CREATE TABLE IF NOT EXISTS role_permissions (
    role_id       integer NOT NULL REFERENCES roles(role_id) ON DELETE CASCADE,
    permission_id integer NOT NULL REFERENCES permissions(permission_id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE IF NOT EXISTS user_roles (
    user_id integer NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    role_id integer NOT NULL REFERENCES roles(role_id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, role_id)
);

-- NULL rows = access to every branch
CREATE TABLE IF NOT EXISTS user_branches (
    user_id   integer NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    branch_id integer NOT NULL REFERENCES branches(branch_id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, branch_id)
);

CREATE TABLE IF NOT EXISTS app_settings (
    setting_key   varchar(120) PRIMARY KEY,
    setting_value text,
    updated_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS periods (
    period_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id   integer NOT NULL REFERENCES branches(branch_id),
    name        varchar(120) NOT NULL,
    start_date  date NOT NULL,
    end_date    date,
    is_closed   boolean NOT NULL DEFAULT false,
    closed_at   timestamptz,
    closed_by   integer REFERENCES users(user_id),
    notes       text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (branch_id, name)
);

