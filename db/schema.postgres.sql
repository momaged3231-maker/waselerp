    stock_operation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_no   varchar(60) NOT NULL UNIQUE,
    operation_type smallint NOT NULL,   -- 1 transfer, 2 count, 3 adjustment
    branch_id      integer NOT NULL REFERENCES branches(branch_id),
    from_warehouse_id integer REFERENCES warehouses(warehouse_id),
    to_warehouse_id   integer REFERENCES warehouses(warehouse_id),
    operation_date timestamptz NOT NULL DEFAULT now(),
    status         smallint NOT NULL DEFAULT 1,   -- 1 draft, 2 approved
    notes          text,
    created_by     integer NOT NULL REFERENCES users(user_id),
    approved_by    integer REFERENCES users(user_id),
    approved_at    timestamptz,
    created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS stock_operation_lines (
