CREATE TABLE IF NOT EXISTS invoices (
    invoice_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no      varchar(60)  NOT NULL,
    invoice_type    smallint NOT NULL,   -- 1 sales, 2 purchase, 3 sales return, 4 purchase return
    branch_id       integer NOT NULL REFERENCES branches(branch_id),
    warehouse_id    integer NOT NULL REFERENCES warehouses(warehouse_id),
    party_id        integer REFERENCES parties(party_id),
    invoice_date    timestamptz NOT NULL DEFAULT now(),
    due_date        date,
    period_id       integer REFERENCES periods(period_id),
    status          smallint NOT NULL DEFAULT 1,   -- 1 open, 2 posted, 3 cancelled
    payment_type    smallint NOT NULL DEFAULT 1,   -- 1 cash, 2 credit, 3 mixed
    sub_total       numeric(18,2) NOT NULL DEFAULT 0,
    discount_amount numeric(18,2) NOT NULL DEFAULT 0,
    discount_pct    numeric(9,4) NOT NULL DEFAULT 0,
    tax_amount      numeric(18,2) NOT NULL DEFAULT 0,
    total_amount    numeric(18,2) NOT NULL DEFAULT 0,
    paid_amount     numeric(18,2) NOT NULL DEFAULT 0,
    cost_total      numeric(18,2) NOT NULL DEFAULT 0,
    profit_amount   numeric(18,2) NOT NULL DEFAULT 0,
    cash_account_id integer,
    rep_id          integer REFERENCES users(user_id),
    cashier_id      integer REFERENCES users(user_id),
    created_by      integer NOT NULL REFERENCES users(user_id),
    notes           text,
    is_posted       boolean NOT NULL DEFAULT false,
    posted_at       timestamptz,
    parent_invoice_id bigint REFERENCES invoices(invoice_id),
    client_request_id varchar(64),
    created_at      timestamptz NOT NULL DEFAULT now(),
    version         integer NOT NULL DEFAULT 1,
    UNIQUE (invoice_no, invoice_type)
);
CREATE INDEX IF NOT EXISTS ix_invoices_branch_date_type ON invoices(branch_id, invoice_date, invoice_type);
CREATE INDEX IF NOT EXISTS ix_invoices_party ON invoices(party_id);
CREATE UNIQUE INDEX IF NOT EXISTS ux_invoices_client_request ON invoices(client_request_id) WHERE client_request_id IS NOT NULL;

