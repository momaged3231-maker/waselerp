CREATE TABLE IF NOT EXISTS cash_accounts (
    cash_account_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id      integer NOT NULL REFERENCES branches(branch_id),
    name           varchar(200) NOT NULL,
    type           smallint NOT NULL DEFAULT 1,  -- 1 drawer, 2 bank, 3 card, 4 wallet
    account_no     varchar(60),
    bank_name      varchar(200),
    currency_code  varchar(10) NOT NULL DEFAULT 'EGP',
    opening_balance numeric(18,2) NOT NULL DEFAULT 0,
    is_active      boolean NOT NULL DEFAULT true,
    notes          text
);

CREATE TABLE IF NOT EXISTS cash_categories (
    cash_category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(200) NOT NULL,
    direction  smallint NOT NULL,   -- 1 in, 2 out
    notes      text
);

CREATE TABLE IF NOT EXISTS cash_transactions (
    cash_transaction_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id      integer NOT NULL REFERENCES branches(branch_id),
    cash_account_id integer NOT NULL REFERENCES cash_accounts(cash_account_id),
    direction      smallint NOT NULL,   -- 1 in, 2 out
    category_id    integer REFERENCES cash_categories(cash_category_id),
    amount         numeric(18,2) NOT NULL DEFAULT 0,
    transaction_date timestamptz NOT NULL DEFAULT now(),
    description    text,
    party_id       integer REFERENCES parties(party_id),
    invoice_id     bigint REFERENCES invoices(invoice_id),
    transfer_group_id bigint,
    period_id      integer REFERENCES periods(period_id),
    shift_id       bigint,
    created_by     integer NOT NULL REFERENCES users(user_id),
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_cash_tx_account_date ON cash_transactions(cash_account_id, transaction_date);

CREATE TABLE IF NOT EXISTS shifts (
    shift_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id     integer NOT NULL REFERENCES branches(branch_id),
    cash_account_id integer NOT NULL REFERENCES cash_accounts(cash_account_id),
    cashier_id    integer NOT NULL REFERENCES users(user_id),
    shift_no      integer NOT NULL,
    opened_at     timestamptz NOT NULL DEFAULT now(),
    closed_at     timestamptz,
    opening_balance numeric(18,2) NOT NULL DEFAULT 0,
    expected_cash numeric(18,2) NOT NULL DEFAULT 0,
    counted_cash  numeric(18,2),
    difference    numeric(18,2),
    status        smallint NOT NULL DEFAULT 1,   -- 1 open, 2 closed
    notes         text
);

