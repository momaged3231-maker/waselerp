CREATE TABLE IF NOT EXISTS parties (
    party_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             varchar(30),
    name             varchar(300) NOT NULL,
    name_en          varchar(300),
    party_type       smallint NOT NULL,           -- 1 customer, 2 supplier, 3 both
    branch_id        integer REFERENCES branches(branch_id),
    address          text,
    phone            varchar(50),
    mobile           varchar(50),
    email            varchar(200),
    tax_number       varchar(60),
    city             varchar(100),
    area             varchar(100),
    credit_limit     numeric(18,2) NOT NULL DEFAULT 0,
    discount_pct     numeric(9,4) NOT NULL DEFAULT 0,
    price_list_id    integer,
    sales_rep_id     integer REFERENCES users(user_id),
    opening_balance  numeric(18,2) NOT NULL DEFAULT 0,
    notes            text,
    is_active        boolean NOT NULL DEFAULT true,
    created_at       timestamptz NOT NULL DEFAULT now(),
    version          integer NOT NULL DEFAULT 1
);
CREATE INDEX IF NOT EXISTS ix_parties_type_name ON parties(party_type, name);

CREATE TABLE IF NOT EXISTS items (
    item_id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             varchar(60) NOT NULL UNIQUE,
    barcode          varchar(60),
    name             varchar(400) NOT NULL,
    name_en          varchar(400),
    category_id      integer REFERENCES categories(category_id),
    base_unit_id     integer NOT NULL REFERENCES units(unit_id),
    is_service       boolean NOT NULL DEFAULT false,
    is_grouped       boolean NOT NULL DEFAULT false,
    has_serial       boolean NOT NULL DEFAULT false,
    has_expiry       boolean NOT NULL DEFAULT false,
    has_batch        boolean NOT NULL DEFAULT false,
    track_quantity   boolean NOT NULL DEFAULT true,
    cost_price       numeric(18,4) NOT NULL DEFAULT 0,
    sell_price       numeric(18,4) NOT NULL DEFAULT 0,
    whole_sale_price numeric(18,4),
    min_price        numeric(18,4) NOT NULL DEFAULT 0,
    vat_pct          numeric(9,4) NOT NULL DEFAULT 0,
    discount_pct     numeric(9,4) NOT NULL DEFAULT 0,
    reorder_point    numeric(18,4) NOT NULL DEFAULT 0,
    max_stock        numeric(18,4),
    image_path       text,
    is_active        boolean NOT NULL DEFAULT true,
    notes            text,
    created_at       timestamptz NOT NULL DEFAULT now(),
    version          integer NOT NULL DEFAULT 1
);
CREATE INDEX IF NOT EXISTS ix_items_barcode ON items(barcode);
CREATE INDEX IF NOT EXISTS ix_items_name ON items(name);

CREATE TABLE IF NOT EXISTS item_units (
    item_unit_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id      integer NOT NULL REFERENCES items(item_id) ON DELETE CASCADE,
    unit_id      integer NOT NULL REFERENCES units(unit_id),
    factor       numeric(18,6) NOT NULL DEFAULT 1,   -- base units per this unit
    sell_price   numeric(18,4),
    buy_price    numeric(18,4),
    min_price    numeric(18,4),
    is_default   boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS item_components (
    item_component_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_item_id integer NOT NULL REFERENCES items(item_id) ON DELETE CASCADE,
    child_item_id  integer NOT NULL REFERENCES items(item_id),
    quantity       numeric(18,6) NOT NULL DEFAULT 1,
    unit_id        integer REFERENCES units(unit_id)
);

CREATE TABLE IF NOT EXISTS price_lists (
    price_list_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(200) NOT NULL,
    code          varchar(50),
    -- 1 retail (نقدي), 2 wholesale (جملة), 3 half wholesale (نصف جملة)
    list_type     smallint NOT NULL DEFAULT 1,
    branch_id     integer REFERENCES branches(branch_id),
    -- higher priority wins when several lists match
    priority      integer NOT NULL DEFAULT 0,
    discount_pct  numeric(9,4) NOT NULL DEFAULT 0,
    start_date    date,
    end_date      date,
    notes         text,
    is_active     boolean NOT NULL DEFAULT true,
    created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS price_list_lines (
    price_list_line_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_list_id integer NOT NULL REFERENCES price_lists(price_list_id) ON DELETE CASCADE,
    item_id       integer NOT NULL REFERENCES items(item_id) ON DELETE CASCADE,
    unit_id       integer REFERENCES units(unit_id),
    price         numeric(18,4) NOT NULL,
    min_price     numeric(18,4) NOT NULL DEFAULT 0,
    start_date    date,
    end_date      date,
    UNIQUE (price_list_id, item_id, unit_id)
);

