<#
  WaselERP Print Agent - Windows auto-start installer.

  Registers a Scheduled Task so the agent starts with Windows (before/without
  anyone opening a terminal), restarts itself if it crashes, and keeps its
  token/port in apps\print-agent\agent.env.

  Usage (run PowerShell as Administrator):

    .\install-service.ps1 -Token "change-me" -DefaultPrinter "POS-80C"

    .\install-service.ps1 -Token "change-me" -User "SERVER-PC\cashier"

    .\install-service.ps1 -Uninstall
#>
param(
  [string]$Token = "",
  [int]$Port = 4100,
  [string]$DefaultPrinter = "",
  [string]$User = "",              # empty = run as SYSTEM at startup
  [switch]$Uninstall
)

$ErrorActionPreference = 'Stop'
$taskName = 'WaselPrintAgent'
$agentDir = $PSScriptRoot

function Assert-Admin {
  $identity = [Security.Principal.WindowsIdentity]::GetCurrent()
  $principal = New-Object Security.Principal.WindowsPrincipal($identity)
  $isAdmin = $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
  if (-not $isAdmin) { throw 'Run this script from an elevated PowerShell (Run as Administrator).' }
}

Assert-Admin

if ($Uninstall) {
  $existing = Get-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue
  if ($existing) {
    Stop-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue
    Unregister-ScheduledTask -TaskName $taskName -Confirm:$false
    Write-Host "[wasel] removed scheduled task '$taskName'."
  } else {
    Write-Host "[wasel] scheduled task '$taskName' is not installed."
  }
  Get-Process node -ErrorAction SilentlyContinue |
    Where-Object { $_.Path -and (Get-CimInstance Win32_Process -Filter "ProcessId=$($_.Id)").CommandLine -match 'print-agent' } |
    Stop-Process -Force -ErrorAction SilentlyContinue
  return
}

$node = (Get-Command node -ErrorAction SilentlyContinue).Source
if (-not $node) { throw 'node.exe was not found in PATH. Install Node.js 18+ first.' }
if (-not (Test-Path (Join-Path $agentDir 'server.js'))) { throw "server.js not found in $agentDir" }

# --- 1. token + port ------------------------------------------------------
if (-not $Token) {
  $Token = -join ((48..57) + (65..90) + (97..122) | Get-Random -Count 40 | ForEach-Object { [char]$_ })
  Write-Host "[wasel] no token supplied; generated a random one."
}
$envFile = Join-Path $agentDir 'agent.env'
@(
  "# WaselERP Print Agent - generated by install-service.ps1"
  "WASEL_AGENT_TOKEN=$Token"
  "AGENT_PORT=$Port"
  "AGENT_HOST=127.0.0.1"
) | Set-Content -Path $envFile -Encoding UTF8

# --- 2. optional default printer -----------------------------------------
if ($DefaultPrinter) {
  $configPath = Join-Path $agentDir 'agent-config.json'
  $config = @{ defaultPrinter = $DefaultPrinter; networkPrinters = @(); autoOpenDrawer = $false; paperWidth = 42 }
  if (Test-Path $configPath) {
    try { $config = Get-Content $configPath -Raw | ConvertFrom-Json } catch { }
    $config | Add-Member -NotePropertyName defaultPrinter -NotePropertyValue $DefaultPrinter -Force
  }
  $config | ConvertTo-Json -Depth 5 | Set-Content -Path $configPath -Encoding UTF8
  Write-Host "[wasel] default printer set to '$DefaultPrinter'."
}

# --- 3. task action -------------------------------------------------------
$wrapper = Join-Path $agentDir 'run-agent.ps1'
$args = "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$wrapper`""
$action = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument $args -WorkingDirectory $agentDir

if ($User) {
  $trigger = New-ScheduledTaskTrigger -AtLogOn -User $User
  $principal = New-ScheduledTaskPrincipal -UserId $User -LogonType Interactive -RunLevel Highest
} else {
  $trigger = New-ScheduledTaskTrigger -AtStartup
  $principal = New-ScheduledTaskPrincipal -UserId 'SYSTEM' -LogonType ServiceAccount -RunLevel Highest
}

$settings = New-ScheduledTaskSettingsSet `
  -AllowStartIfOnBatteries `
  -DontStopIfGoingOnBatteries `
  -StartWhenAvailable `
  -RestartCount 999 `
  -RestartInterval (New-TimeSpan -Minutes 1) `
  -ExecutionTimeLimit (New-TimeSpan -Days 0)

Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger `
  -Principal $principal -Settings $settings -Force | Out-Null

Start-ScheduledTask -TaskName $taskName
Start-Sleep -Seconds 2

$health = try { Invoke-RestMethod -Uri "http://127.0.0.1:$Port/health" -TimeoutSec 5 } catch { $null }

Write-Host ""
Write-Host "[wasel] scheduled task '$taskName' installed and started."
Write-Host "[wasel] token: $Token"
Write-Host "[wasel] env file: $envFile"
Write-Host "[wasel] logs: $(Join-Path $agentDir 'agent.log')"
if ($health) {
  Write-Host "[wasel] health check: OK ($($health.agent) v$($health.version), port $($health.port))"
} else {
  Write-Warning "[wasel] health check failed. Inspect agent.log and 'Get-ScheduledTaskInfo $taskName'."
}
Write-Host ""
Write-Host "Put this in the web build environment (apps/web/.env.local) before 'npm run web:build':"
Write-Host "  NEXT_PUBLIC_AGENT_BASE=http://127.0.0.1:$Port"
Write-Host "  NEXT_PUBLIC_AGENT_TOKEN=$Token"
