<#
  WaselERP Print Agent - installer for a cashier PC.

  Run from an elevated PowerShell:
    cd C:\wasel\print-agent
    .\install.ps1 -Token "wasel-local-agent" -DefaultPrinter "POS-80C"

  What it does:
    1. Checks Node.js 18+.
    2. Runs `npm install` if node_modules is missing.
    3. Writes agent.env (token + port).
    4. (Optional) sets default printer in agent-config.json.
    5. Registers a Scheduled Task (auto-start at boot, auto-restart) running
       run-agent.ps1. Use -User "PC\cashier" to run as an interactive user
       (recommended when Windows printers are installed for that user);
       default runs as SYSTEM (good for TCP 9100 network printers).
    6. Starts the task and verifies health on http://127.0.0.1:4100.
#>
param(
  [string]$Token = "",
  [int]$Port = 4100,
  [string]$DefaultPrinter = "",
  [string]$User = "",
  [switch]$Uninstall
)

$ErrorActionPreference = 'Stop'
$taskName = 'WaselPrintAgent'
$agentDir = $PSScriptRoot

function Assert-Admin {
  $id = [Security.Principal.WindowsIdentity]::GetCurrent()
  $pr = New-Object Security.Principal.WindowsPrincipal($id)
  if (-not $pr.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    throw 'Run this script from an elevated PowerShell (Run as Administrator).'
  }
}
Assert-Admin

if ($Uninstall) {
  $t = Get-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue
  if ($t) {
    Stop-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue
    Unregister-ScheduledTask -TaskName $taskName -Confirm:$false
    Write-Host "[wasel] removed scheduled task '$taskName'."
  } else {
    Write-Host "[wasel] scheduled task '$taskName' is not installed."
  }
  Get-Process node -ErrorAction SilentlyContinue |
    Where-Object { $_.Path -and (Get-CimInstance Win32_Process -Filter "ProcessId=$($_.Id)").CommandLine -match 'print-agent' } |
    Stop-Process -Force -ErrorAction SilentlyContinue
  return
}

# 1. Node.js
$node = (Get-Command node -ErrorAction SilentlyContinue).Source
if (-not $node) {
  Write-Host "[wasel] Node.js not found."
  Write-Host "  Install Node.js 18+ from https://nodejs.org  (LTS, 'Next/Next/Install'), then re-run this script."
  exit 1
}
$nodeVer = & node --version
Write-Host "[wasel] Node.js: $nodeVer"

# 2. npm install (if needed)
if (-not (Test-Path (Join-Path $agentDir 'node_modules'))) {
  Write-Host "[wasel] installing dependencies..."
  Push-Location $agentDir
  & npm install
  Pop-Location
}

# 3. token
if (-not $Token) {
  $Token = -join ((48..57) + (65..90) + (97..122) | Get-Random -Count 40 | ForEach-Object { [char]$_ })
  Write-Host "[wasel] no token supplied; generated a random one."
}
$envFile = Join-Path $agentDir 'agent.env'
@(
  "# WaselERP Print Agent - generated by install.ps1"
  "WASEL_AGENT_TOKEN=$Token"
  "AGENT_PORT=$Port"
  "AGENT_HOST=127.0.0.1"
  "WASEL_SERVER_BASE=http://localhost:4000/api"
  "WASEL_AGENT_SECRET=wasel-agent-secret-2026"
) | Set-Content -Path $envFile -Encoding UTF8
Write-Host "[wasel] wrote $envFile"

# 4. default printer
if ($DefaultPrinter) {
  $cfgPath = Join-Path $agentDir 'agent-config.json'
  $cfg = @{ defaultPrinter = $DefaultPrinter; networkPrinters = @(); autoOpenDrawer = $false; paperWidth = 42 }
  if (Test-Path $cfgPath) {
    try { $cfg = Get-Content $cfgPath -Raw | ConvertFrom-Json } catch { }
    $cfg.defaultPrinter = $DefaultPrinter
  }
  $cfg | ConvertTo-Json -Depth 5 | Set-Content -Path $cfgPath -Encoding UTF8
  Write-Host "[wasel] default printer set to '$DefaultPrinter'."
}

# 5. scheduled task
$wrapper = Join-Path $agentDir 'run-agent.ps1'
$action = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$wrapper`"" -WorkingDirectory $agentDir

if ($User) {
  $trigger = New-ScheduledTaskTrigger -AtLogOn -User $User
  $principal = New-ScheduledTaskPrincipal -UserId $User -LogonType Interactive -RunLevel Highest
} else {
  $trigger = New-ScheduledTaskTrigger -AtStartup
  $principal = New-ScheduledTaskPrincipal -UserId 'SYSTEM' -LogonType ServiceAccount -RunLevel Highest
}

$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1) -ExecutionTimeLimit (New-TimeSpan -Days 0)

# remove old
$existing = Get-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue
if ($existing) {
  Stop-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue
  Unregister-ScheduledTask -TaskName $taskName -Confirm:$false
}
Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger -Principal $principal -Settings $settings -Force | Out-Null
Start-ScheduledTask -TaskName $taskName
Start-Sleep -Seconds 3

# 6. health check
$health = try { Invoke-RestMethod -Uri "http://127.0.0.1:$Port/health" -TimeoutSec 5 } catch { $null }
Write-Host ""
Write-Host "[wasel] scheduled task '$taskName' installed and started."
Write-Host "[wasel] token: $Token"
Write-Host "[wasel] env file: $envFile"
Write-Host "[wasel] logs: $(Join-Path $agentDir 'agent.log')"
if ($health) {
  Write-Host "[wasel] health check: OK ($($health.agent) v$($health.version), port $($health.port))"
} else {
  Write-Warning "[wasel] health check failed. Inspect agent.log."
}
Write-Host ""
Write-Host "Put this in the web build environment (apps/web/.env.local) before 'npm run web:build':"
Write-Host "  NEXT_PUBLIC_AGENT_BASE=http://127.0.0.1:$Port"
Write-Host "  NEXT_PUBLIC_AGENT_TOKEN=$Token"
Write-Host ""
Write-Host "Cloud (cross-location) is enabled: the agent registers itself with the"
Write-Host "server (WASEL_SERVER_BASE) and polls for print jobs. To point at a"
Write-Host "remote server, edit WASEL_SERVER_BASE in agent.env and restart the task."
